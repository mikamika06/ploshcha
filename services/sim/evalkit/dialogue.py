"""Числа про саму РОЗМОВУ: різність слів — і зчеплення реплік між собою.

Різність (`distinctness`, `overlap`) жила в `scripts/probe_viche.py` і міряла неповторюваність.
Вона лишається тут без жодної зміни формули, але поруч із нею тепер стоїть зчеплення, бо
поодинці перша брехала: на чотирьох живих прогонах аудиту `distinct2` показував 0.93-0.97, тобто
зелене, тоді як 60.6% пар реплік не мали між собою ЖОДНОЇ ознаки звʼязку
(`docs/research/dialogue-audit.md`). Прилад міряв слова, а скарга власника була про діалог.
"""

import re

from ploshcha_sim.agents.viche import (
    LEAK_GRAM,
    LINE_SYSTEM,
    NAME_ENDING,
    OWN_MEANING,
    OWN_STEMS,
    PICKUP_STEMS,
    _leak_len,
    _name_roots,
    _stems,
)
from ploshcha_sim.domain.viche import PIP, STAROSTA, VOTES


def ngrams(text: str, n: int) -> set[tuple[str, ...]]:
    words = text.lower().split()
    return {tuple(words[i:i + n]) for i in range(max(0, len(words) - n + 1))}


def distinctness(lines: list[str], n: int = 2) -> float:
    """Частка унікальних n-грам. Низька = всі говорять однаково (ризик обвалу ентропії Lapa)."""
    total, uniq = 0, set()
    for line in lines:
        words = line.lower().split()
        grams = [tuple(words[i:i + n]) for i in range(max(0, len(words) - n + 1))]
        total += len(grams)
        uniq |= set(grams)
    return len(uniq) / total if total else 0.0


def overlap(lines: list[str], n: int = 2) -> float:
    """Середнє попарне перекриття n-грам між репліками — пряма міра «всі однакові»."""
    grams = [ngrams(t, n) for t in lines]
    pairs = [(i, j) for i in range(len(grams)) for j in range(i + 1, len(grams))]
    if not pairs:
        return 0.0
    scores = []
    for i, j in pairs:
        union = grams[i] | grams[j]
        scores.append(len(grams[i] & grams[j]) / len(union) if union else 0.0)
    return sum(scores) / len(scores)


# Хто закриває віче, а не розмовляє: староста зводить, піп сумнівається — обидва говорять ПРО
# розмову, а не в ній, і пара «остання репліка → зведення» ознак звʼязку мати не зобовʼязана.
CLOSERS = frozenset({STAROSTA.name, PIP.name})

# Скільки спільних змістових основ ПОЗА словами новини вже досить, щоб назвати це підхопленням.
# Двійка — не смак: на одній основі ознака вироджується (двоє кажуть «село» — і це вже нібито
# діалог). Число береться з ядра, а не переписується сюди: тим самим порогом відбір реплік тепер
# ВІДДАЄ ПЕРЕВАГУ варіантові, що чіпляється (`agents/viche.py`, `_picked_up`), і розійтись їм не
# можна — інакше прилад міряв би не те, що робить сторож.
PICKUP = PICKUP_STEMS

# Порожній зачин, який нічого не відповідає сам собою: його знімаємо перед тим, як дивитись на
# перше змістове слово. Без цього «Та то ж було торік, як я парубкував» лічилось би реакцією
# нарівні з «Та ні, то не вовк» — заміряно, саме «та» давало 303 хибні спрацювання з 352.
LEAD = frozenset("та а ой ну е ех ага".split())

# Слова, якими не ПОЧИНАЮТЬ тему — ними лише відгукуються на щойно сказане: згода, заперечення,
# перепит. Список закритий навмисно: відкритий (будь-яка частка на початку) дав 47.4% пар проти
# 25.8% ручної розмітки аудиту, тобто міряв би не реакцію, а манеру.
REACTION = frozenset("""
ні так еге авжеж атож звісно отож справді правда згоден згодна згода годі
хіба невже чи дарма неправда брехня ото оце але проте однак
""".split())

# Ті самі відгуки, які тримаються лише парою слів: «не» саме по собі відкриває будь-яку думку,
# «не вірю» — тільки відповідь на чиюсь; «що» так само, а «що ти» й «що ви» — перепит.
REACTION_PAIR = frozenset([
    "не вірю", "не згоден", "не згодна", "не правда", "не чув", "не бачив",
    "де там", "куди там", "що ти", "що ви", "що там", "що ж", "як то", "як же",
])


def _rows(transcript: list[str]) -> list[tuple[str, str]]:
    """Стенограма «Імʼя: текст» → пари. Рядок без підпису не репліка, а уламок — його немає."""
    out = []
    for line in transcript or []:
        if ": " not in line:
            continue
        who, text = line.split(": ", 1)
        out.append((who.strip(), text.strip()))
    return out


def _voted(text: str) -> bool:
    """Голос — не репліка: `за`/`проти`/`утримуюсь` відповідають старості, а не сусідові."""
    head = (text or "").strip(" .,!?–—").lower().split(" ")[0].strip(" .,!?–—")
    return head in VOTES


def _talk(transcript: list[str]) -> list[tuple[str, str]]:
    return [(who, text) for who, text in _rows(transcript)
            if who.lower() not in CLOSERS and not _voted(text)]


def _words(text: str) -> list[str]:
    words = (w.strip(".,!?«»\"'—-…:;()").lower() for w in (text or "").split())
    return [w for w in words if w]


def picked_up(line: str, earlier: str, task: str = "") -> bool:
    """Чи підхопив мовець ЩОСЬ СВОЄ з попередньої репліки, а не слова самої новини.

    Новину відкидаємо, бо без цього «звʼязком» стає те, що всі кажуть слово «вовк»: на корпусі
    аудиту спільна основа разом зі словами новини давала 48.5% пар, а без них — 13.6%.

    Основу бере той самий `_stems`, що й сторожі повторів, — і не лише заради однієї мови з ними.
    Заміряно на 743 парах збережених прогонів: його пʼять літер дають 13.9% підхоплень (ручна
    розмітка — 13.6%), чотири літери — 10.4%, бо коротший префікс дужче злипається зі словами
    новини й віднімається разом із ними, шість — 13.6%.
    """
    return len((_stems(earlier) & _stems(line)) - _stems(task)) >= PICKUP


# Стеля довжини репліки, на якій підхоплення міряється чесно, і людська норма на цій стелі.
#
# Підхоплення — це лічба спільних основ, а довша репліка має більше основ, тож число росте з
# ДОВЖИНОЮ рядка, а не зі звʼязністю. Заміряно на двох українських пʼєсах (`docs/research/
# dialogue-tier-vs-content.md`, дослід 3): «Бондарівна» дає 32 із 280 = 11.4% без стелі, 2 із 79 =
# 2.5% при ≤20 словах, 2 із 54 = 3.7% при ≤16 і 0 із 40 = 0.0% при ≤12; «Мина Мазайло» — 6.7%,
# 4.1%, 2.8%, 1.0%. Поки ворота стоять на числі БЕЗ стелі, будь-яка правка, що вкорочує репліку,
# виглядає регресом звʼязності, а будь-яка, що подовжує, — поліпшенням, і жодна з двох оцінок не
# про діалог. Шістнадцять — не смак: це та стеля, на якій обидві пʼєси ще дають по кілька десятків
# пар (54 і 145) і на якій лежить наша власна довжина рядка (11.8-15.7 слова в трьох плечах
# `packet-strip.md`).
LENGTH_CEILING = 16

# Людський еталон: 6 пар із 199 = 3.0% на репліках до 16 слів у двох пʼєсах разом (2 із 54 у
# «Бондарівні» 1916 року, 4 із 145 у «Мині Мазайлі» 1929-го), той самий `_stems` і той самий
# поріг `PICKUP`. Ціль «13% підхоплення» походить із ручної розмітки НАШОГО корпусу
# (`docs/research/dialogue-audit.md`), а не з людської розмови: класик українського театру,
# суджений цим самим приладом на нашій довжині рядка, дає 3%, і ми на ній стоїмо.
#
# Еталон знято БЕЗ віднімання теми, бо спільної новини в пʼєси немає, а наше число віднімає
# (`picked_up(..., task)`). Асиметрія навмисна й на нашу шкоду: віднімання може лише зменшити
# наше число, тож «до еталона» ніколи не лестить.
PLAY_PICKUP = 0.030


def _said(text: str) -> int:
    """Довжина репліки в словах — простим `split`, як її рахували на пʼєсах.

    Не `_words`: той зрізає розділові знаки й викидає порожні токени, а еталон пʼєс знято
    `len(text.split())`. Розійшовшись на тире й трикрапках, лінійка міряла б наші репліки трохи
    коротшими за людські — тобто саме тим зміщенням, проти якого вся ця стеля й ставиться.
    """
    return len((text or "").split())


def aligned_pickup(transcript: list[str], task: str = "",
                   ceiling: int = LENGTH_CEILING) -> dict:
    """★ ПІДХОПЛЕННЯ З ВИРІВНЮВАННЯМ НА ДОВЖИНУ — і відстань до людського еталона пʼєс.

    Голе `picked_up` є функцією довжини репліки, і це заміряно, а не припущено: та сама пʼєса дає
    6.7% без стелі, 4.1% при рядках до 20 слів, 2.8% при 16 і 1.0% при 12 (`docs/research/
    dialogue-tier-vs-content.md`, дослід 3). Тому число «як є» лишається в звіті, але поруч із ним
    тепер стоїть друге, зняте лише з тих пар, де ОБИДВІ репліки не довші за стелю, — і третє,
    середня довжина репліки, без якої перші два не читаються.

    Що вирівнювання справді знімає саме довжину, а не зміст, перевірено на всіх 43 збережених
    прогонах зі стенограмою (`docs/research/eval-runs/aligned-recount.py`, 1112 пар): звʼязок
    середньої довжини репліки з голим підхопленням r = 0.661, а з вирівняним — r = 0.023 на тих
    25 прогонах, де є хоч одна пара під стелею.

    Пара береться цілком: якщо довга хоч одна з двох реплік, пара випадає. Довга відповідь на
    коротку репліку має більше основ, тобто більше шансів збігтись, — і саме цей шанс тут
    вимикається.

    `до_еталона` — у частках, а не у відсоткових пунктах, і рахується від `PLAY_PICKUP` (3.0%
    людської норми на цій же стелі). Мінус означає «нижче за людину», плюс — «вище».

    ★ Коли жодна пара не влазить у стелю, `вирівняне` — це `None`, а не нуль. Нуль читався б як
    «підхоплення немає», хоч насправді немає ЗАМІРУ: рівно та підміна, через яку попередні круги
    записували в регрес правки, що вкоротили репліку.
    """
    rows = _talk(transcript)
    pairs = [(a, b) for a, b in zip(rows, rows[1:]) if a[0] != b[0]]
    short = [(a, b) for a, b in pairs if _said(a[1]) <= ceiling and _said(b[1]) <= ceiling]
    hits = sum(1 for (_, before), (_, text) in pairs if picked_up(text, before, task))
    short_hits = sum(1 for (_, before), (_, text) in short if picked_up(text, before, task))
    lens = [_said(text) for _, text in rows]
    aligned = round(short_hits / len(short), 3) if short else None
    return {
        "вирівняне": aligned,
        "як_є": round(hits / len(pairs), 3) if pairs else 0.0,
        "пар": len(pairs),
        # Самі лічильники, а не самі частки: зведення багатьох прогонів в одне число інакше
        # довелось би відновлювати множенням округленої частки на кількість пар, а це вже не
        # замір, а його переказ.
        "підхоплень": hits,
        "пар_у_стелі": len(short),
        "підхоплень_у_стелі": short_hits,
        "стеля": ceiling,
        "слів": round(sum(lens) / len(lens), 1) if lens else 0.0,
        "еталон": PLAY_PICKUP,
        "до_еталона": None if aligned is None else round(aligned - PLAY_PICKUP, 3),
    }


def addressed(line: str, name: str) -> bool:
    """Чи назвав мовець того, хто говорив перед ним, — у будь-якому відмінку.

    Порівнюємо основи, як і сторож `_self_named`: інакше «Одарко» й «Одарці» лічились би різними
    людьми, тобто ознака гасла б рівно на тій формі, якою звертаються.
    """
    roots = _name_roots(name)
    if not roots:
        return False
    for word in re.findall(r"[а-яіїєґ']+", (line or "").lower()):
        if any(word.startswith(r) and len(word) - len(r) <= NAME_ENDING for r in roots):
            return True
    return False


def reacted(line: str) -> bool:
    """Чи починається репліка з відгуку на щойно сказане — згоди, заперечення, перепиту."""
    words = _words(line)
    start = 0
    while start < len(words) and start < 2 and words[start] in LEAD:
        start += 1
    rest = words[start:]
    if not rest:
        return False
    return rest[0] in REACTION or (len(rest) > 1 and " ".join(rest[:2]) in REACTION_PAIR)


def coherence(transcript: list[str], task: str = "") -> dict:
    """★ ЗЧЕПЛЕННЯ: частка сусідніх пар реплік, у яких видно хоч одну ознаку звʼязку.

    Це те саме число, яке аудит рахував руками (`docs/research/dialogue-audit.md`, розділ 2) і
    яким власник називає головну ваду: «пар без жодної ознаки звʼязку 60.5%». Доти воно жило лише
    в разовому аудиті, тож жодна правка не могла показати, зрушила вона його чи ні.

    Три ознаки, усі з тієї ж ручної розмітки: підхоплення теми попередньої репліки поза словами
    новини (`picked_up`), звертання до попереднього мовця (`addressed`), зачин-реакція
    (`reacted`). Пара лічиться зчепленою, якщо є ХОЧ ОДНА.

    Звірено з ручною розміткою на 743 парах 53 збережених прогонів `docs/research/eval-runs`:
    підхоплення 13.9% проти 13.6% в аудиті, звертання 6.9% проти 6.1%, реакція 21.7% проти 25.8%,
    хоч одна 36.3% проти 39.4%. Метрика систематично трохи СКУПІША за людину, і це навмисно: краще
    не помітити звʼязок, ніж намалювати його там, де його немає.

    Розкид на тому ж корпусі: від 0.059 (18 реплік, з яких дві — протік службового тексту в
    сцену) до 0.684; медіана 0.353. У найгірших прогонах підхоплення й звертання рівно нулі, у
    найкращих обидві ознаки живі, тож розділяє їх не одна лексика зачинів.

    ★ Саме по собі це число НЕ докір і не похвала: хор із двадцяти «Та що ж воно робиться»
    підніме реакцію й дасть 0.684 при `overlap2` під стелею. Зчеплення читається ПОРУЧ із
    різністю, як і задумано — тому вони й лежать в одному файлі.
    """
    rows = _talk(transcript)
    pairs = [(a, b) for a, b in zip(rows, rows[1:]) if a[0] != b[0]]
    marks = [(picked_up(text, before, task), addressed(text, who), reacted(text))
             for (who, before), (_, text) in pairs]
    linked = sum(1 for m in marks if any(m))
    return {
        "зчеплення": round(linked / len(marks), 3) if marks else 0.0,
        "пар": len(marks),
        "підхоплення": sum(1 for m in marks if m[0]),
        "звертання": sum(1 for m in marks if m[1]),
        "реакція": sum(1 for m in marks if m[2]),
    }


def retelling(transcript: list[str], threshold: float = OWN_MEANING) -> dict:
    """★ ПЕРЕКАЗ ВЛАСНОЇ ДУМКИ: найгірша пара реплік ОДНОГО мовця, а не бінарне «пройшло».

    Аудит назвав це головною нескаргованою вадою («дід Свирид переказує одну історію чотири рази»)
    і вимагав рапортувати найгіршу пару ТЕКСТОМ: саме бінарне «пар понад поріг — нуль» три круги
    поспіль показувало зелене, бо пороги стояли вищі за реальні повтори (`docs/research/
    dialogue-audit.md`, розділ 13).

    Міряється тим самим мішком змістових основ, що й сторож у ядрі (`_same_meaning`), і тим самим
    порогом (`OWN_MEANING` 0.28 при `OWN_STEMS` 2) — інакше прилад і сторож розійшлися б, і число
    перестало б означати «сторож мовчить дарма». Голоси й закривачі відкинуто (`_talk`): на голос
    стоїть окремий сторож у `_vote_why`, а староста з попом говорять ПРО розмову, а не в ній.

    Замір на 31 збереженому прогоні (`docs/research/eval-runs/viche-*.json`): 901 розмовна
    репліка, з них 30 (3.3%) переказують уже сказане тим самим мовцем; найгірша пара — 1.0
    (дослівний дубль шинкаря Лейби), далі 0.818 і 0.714.
    """
    rows = _talk(transcript)
    worst, hits, pair = 0.0, 0, []
    for i, (who, text) in enumerate(rows):
        mine = _stems(text)
        if not mine:
            continue
        for before, earlier in ((b, e) for b, e in rows[:i] if b == who):
            theirs = _stems(earlier)
            common = mine & theirs
            if not theirs or len(common) < OWN_STEMS:
                continue
            score = len(common) / len(mine | theirs)
            if score > worst:
                worst, pair = score, [who, earlier, text]
            if score >= threshold:
                hits += 1
                break
    return {"переказ": round(worst, 3), "переказів": hits, "найгірша_пара": pair}


def leakage(transcript: list[str], task: str = "", packets: tuple[str, ...] = ()) -> dict:
    """★ ПРОТІК ПАКЕТА: найдовший ланцюжок слів, який репліка віддала назад із промпта.

    Це головний борг приладу, названий аудитом двічі (`docs/research/dialogue-audit.md`, розділ 21
    п. 2 і розділ 22 п. 4): флагманська вимога другого круга («підказка не тече») не мала жодного
    постійного числа, тож три круги поспіль її доводили саморобними шпигунами, які потім
    викидали. Закон, який тут міряється, заміряний шість разів на шести різних текстах і
    сформульований там-таки: будь-який вільний текст, покладений у пакет виконавця, вертається
    дослівно.

    Рахує та сама функція, що й сторож у ядрі (`_leak_len`), і тим самим порогом (`LEAK_GRAM` =
    4) — інакше прилад і сторож розійшлися б, і число перестало б означати «сторож мовчить дарма».

    ★ ЧОГО ЦЕ ЧИСЛО НЕ БАЧИТЬ, СКАЗАНО ПРЯМО. Збережений звіт прогону не містить пакетів
    (`probe_viche.py` пише стенограму, лічильники й інциденти), тож без `packets` міряється лише
    та частина промпта, яка відновлюється зі звіту: новина, вона ж тема віча, і сталий текст
    системного повідомлення мовця. Заміряно на 932 розмовних репліках 33 збережених прогонів:
    системне дає щонайбільше 2 слова поспіль на весь корпус (його не переказують, бо воно не
    схоже на мову), тобто вся вага цього числа — новина. Повний пакет доїжджає лише живим
    прогоном через інцидент `viche_leak:{роль}:{довжина}` із ядра.

    Числа на цьому корпусі: ланцюжків ≥ 4 слів — 65 реплік (7.0%), ≥ 5 — 21 (2.3%), тобто поріг
    аудиту бачить утричі більше за пʼятірку `_echoes`. На чотирьох прогонах останнього круга
    (63 репліки) — 0, як і показував тодішній шпигун руками (0 із 33).
    """
    sources = tuple(x for x in ((task or ""), LINE_SYSTEM, *packets) if x)
    worst, hits, where = 0, 0, []
    for who, text in _talk(transcript):
        run = _leak_len(text, *sources)
        if run > worst:
            worst, where = run, [who, text]
        if run >= LEAK_GRAM:
            hits += 1
    return {"протік": worst, "протіків": hits, "найдовший": where if worst >= LEAK_GRAM else []}


def numbers(transcript: list[str], task: str = "") -> dict:
    """Увесь блок чисел про розмову — щоб зчеплення не забули дописати в наступний звіт.

    Різність і зчеплення мусять їхати ОДНИМ шматком, бо поодинці кожне з них бреше в свій бік:
    різність показувала 0.975 там, де звʼязку між репліками не було зовсім (`viche-1787496811`),
    а зчеплення 0.684 дав прогін, де половина села повторює «Та що ж воно робиться»
    (`viche-1787388525`, `overlap2` 0.028 — найгірший з 53 збережених).
    """
    texts = [line.split(": ", 1)[1] for line in transcript or [] if ": " in line]
    bond = coherence(transcript, task)
    told = retelling(transcript)
    leak = leakage(transcript, task)
    length = aligned_pickup(transcript, task)
    return {
        "distinct2": round(distinctness(texts, 2), 3),
        "overlap2": round(overlap(texts, 2), 3),
        "зчеплення": bond["зчеплення"],
        "ознаки_звʼязку": {k: v for k, v in bond.items() if k != "зчеплення"},
        # Переказ власної думки їде ТИМ САМИМ шматком, що різність і зчеплення, з тієї самої
        # причини: три круги поспіль він лишався поза звітом, і кожна правка мусила вірити на
        # слово, що вада на місці.
        "переказ": told["переказ"],
        "перекази": {k: v for k, v in told.items() if k != "переказ"},
        # Протік їде ТИМ САМИМ шматком і з тієї самої причини, що переказ: доти його не було в
        # звіті взагалі, тож кожна правка, яка обіцяла «підказка більше не тече», мусила вірити
        # на слово. Тепер це число, і воно стоїть у воротах наступного круга.
        "протік": leak["протік"],
        "протіки": {k: v for k, v in leak.items() if k != "протік"},
        # Вирівняне підхоплення їде ТИМ САМИМ шматком, бо голе число з `ознаки_звʼязку` — функція
        # довжини репліки, і без стелі поруч воно бреше в обидва боки (6.7% без стелі проти 1.0%
        # при ≤12 словах на тій самій пʼєсі). Разом із ним їдуть середня довжина, якою число
        # пояснюється, і відстань до людського еталона, бо «13% підхоплення» ворітьми бути не
        # може: людина на нашій довжині рядка дає 3.0%.
        "вирівняне": length["вирівняне"],
        "вирівнювання": {k: v for k, v in length.items() if k != "вирівняне"},
    }
