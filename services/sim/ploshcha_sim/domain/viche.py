#
# Обидві хиби ПЛИВКІ, і саме тому їх видно лише на корпусі, а не на окремому вдалому рядку: у
# другому прогоні тих самих сідів «а вчора ще й чоловік мене побив» помилявся 1 раз із 3, а «та він
# мене прибʼє» — 1 раз із 3 замість 3 з 3. Разом по двох прогонах перший рядок хибив 1 раз із 6,
