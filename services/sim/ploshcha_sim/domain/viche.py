def stance_after(beat: Beat, stances: dict[str, float], standing: dict[str, float] | None,
                 fact_found: bool | None,
                 voices: dict[str, str] | None = None) -> dict[str, float]:
    """Як такт зрушив позиції — і того, ХТО сказав, і того, КОМУ сказали.

    Правила ДЕТЕРМІНОВАНІ: це визначено даними, тож належить коду. Вага мовця — його репутація:
    кому спростували чутку, того й слухають менше. Той самий принцип, що вже ріже йому час слова,
    тут ріже і вплив на чужу думку.

    ★ АДРЕСАТ РУХАЄТЬСЯ ВІД ТОГО, ЩО ЙОМУ СКАЗАЛИ. `voices` — той самий довідник «мітка → хто
    сказав», яким уже розвʼязуються стосунки (`bonds_from`) і адреса пакета: без нього мітка
    лишається рядком, а не людиною, і саме тому суперечка не доходила до позицій.

    Знак зсуву дає та сама таблиця, що веде стосунки (`BOND_OF_MOVE`): дружній хід тягне адресата
    ДО мовця, ворожий — від нього. Тягне за РІЗНИЦЮ позицій, а не на сталу величину: переконувати
    того, хто вже стоїть там само, нема чим, а впертись у відповідь на заперечення можна лише в
    той бік, звідки тебе штовхають. Ходи без стосунку (`спитати_діло`, `пожалітись`) адресата не
    рухають зовсім — рівно ті самі, які нічого не роблять і зі стосунками.

    Скільки це важить, заміряно ПЕРЕГРАВАННЯМ трьох живих партитур (2026-08-30, сіди 1 і 2,
    «вовк» і «мито»: 19 + 19 + 14 тактів, 27 із них з адресою, 17 голосів): правило спрацьовує
    приблизно шість разів на віче й зсуває адресата в середньому на 0.10. Знак позиції збігся з
    голосом у 12 із 17 проти 11 із 17 доти, ярлик — у 7 із 17 проти 5. Головне не в частках, а в
    тому, що рух узагалі є: мовчазний довідник сам по собі знерухомлював чотирьох із вісімнадцяти
    (14/18), а разом з адресатом рухомих лишається 16 із 18, як і доти.

    ★ ПОРОЖНІЙ ДОВІДНИК — НЕ ЗАПЕРЕЧЕННЯ. `fact_found=None` означає «інструмента не було або він
    не відповів», а не «факт спростовано», і доти воно читалось як хибне разом із чесним «сходив
    і не знайшов». Ціна цієї однієї літери заміряна перебором усіх послідовностей ходів довжини 3
    (≈ реальність: 19 тактів на шістьох): 65.0% «вагається», 29.1% «проти», 5.9% «за» — при 62.4%
    «за» і НУЛІ «утримуюсь» у 149 живих голосах. Мовчазний довідник тепер не рухає нікого; подія
    «сходив і не знайшов» (`False`) лишається тим, чим була.
    """
    out = dict(stances)
    who = beat.хто
    if who not in out:
        return out
    w = max(0.4, min(1.4, (standing or {}).get(who, 1.0)))

    def move(role: str, delta: float) -> None:
        out[role] = max(STANCE_MIN, min(STANCE_MAX, out.get(role, 0.0) + delta))

    move_kind = beat.хід
    if move_kind == "заперечити":
        move(who, -0.34 * w)
    elif move_kind == "піддакнути":
        move(who, +0.30 * w)
    elif move_kind == "засумніватись":
        move(who, -0.16 * w if out.get(who, 0.0) > 0 else +0.10 * w)
    elif move_kind == "пожалітись":
        move(who, -0.26 * w)
    elif move_kind == "спитати_діло":
        move(who, +0.08 * w)
    elif move_kind in ("згадати", "порахувати") and fact_found is not None:
        # Факт важить більше за слово: знайдена довідка тягне мовця до «за», ненайдена — назад.
        move(who, (+0.28 if fact_found else -0.10) * w)
    # Той, кому це сказали: зсув іде ПІСЛЯ мовцевого, бо тягне саме до нової позиції мовця.
    other = (voices or {}).get(beat.у_відповідь or "")
    tie = BOND_OF_MOVE.get(move_kind, 0.0)
    if other and other != who and other in out and tie:
        pull = tie * ANSWER_PULL * w * (out[who] - out[other])
        move(other, max(-ANSWER_CAP, min(ANSWER_CAP, pull)))
    return out


def stance_view(stances: dict[str, float], cast_names: dict[str, str] | None = None) -> str:
    """Позиції словами — саме це бачить Мамай, плануючи наступну хвилю."""
    if not stances:
        return ""
    parts = [f"{(cast_names or {}).get(r, r)}: {stance_label(v)}" for r, v in stances.items()]
    return "ПОЗИЦІЇ ЗАРАЗ: " + " | ".join(parts)


# Ярлик позиції → голос, який йому відповідає. Третя пара називається різними словами навмисно:
# «вагається» — про думку, «утримуюсь» — про дію, і саме на ній видно розрив. Без цієї таблиці
# звірку коду з моделлю не написати взагалі.
VOTE_OF_STANCE: dict[str, str] = {"за": "за", "проти": "проти", "вагається": "утримуюсь"}


def stance_rows(stances: dict[str, float], cast: list | None = None,
                votes: list | None = None) -> list[dict]:
    """Позиції в тому вигляді, в якому їх можна ЗБЕРЕГТИ у звіт і звірити з голосами.

    ★ Доти позиції не жили ніде, крім локальної змінної прогону: `TaskResult` віддавав самі
    лічильники (`beats=19` тим самим числом у всіх 43 прогонах із нотатками), а в 155 звітах
    `docs/research/eval-runs/` немає ні тактів, ні позицій — `grep 'у_відповідь'` дає нуль
    файлів. Через це жодну гіпотезу про суперечку не можна було перевірити на вже наявних даних,
    і три круги поспіль її міряли тимчасовими шпигунами, яких потім викидали.

    Голос кладеться поруч із позицією одним рядком, бо питання до цих даних одне: чи міряють код
    і модель одне й те саме. Порожній голос — це той, хто говорив, але до лічби не дійшов
    (стеля, тиша, загублена відповідь шлюзу), і він мусить лишитись видимим, а не зникнути.
    """
    names = {p.role: p.name for p in (cast or ())}
    said = {str(v[0]): str(v[1]) for v in (votes or ()) if len(v) >= 2}
    return [{"роль": role, "імʼя": names.get(role, role), "позиція": round(value, 3),
             "ярлик": stance_label(value), "голос": said.get(role, "")}
            for role, value in stances.items()]


# Голос → куди він показує на осі позицій. Потрібен окремо від ярлика, бо ярлик має мертву зону
# ±0.34, а голос її не має: людина, що хилиться на 0.15, ярликом «вагається», а голосує.
SIGN_OF_VOTE: dict[str, int] = {"за": 1, "проти": -1, "утримуюсь": 0}


def stance_match(rows: list[dict]) -> dict:
    """Чи збігається позиція з голосом — тобто чи міряють код і модель одне й те саме.

    Це і є перевірка всієї затії з позиціями. Замір, що її замовив: код при трьох тактах на
    людину казав «вагається» про дві третини села (65.0%), а модель зі 149 живих голосів не
    сказала «утримуюсь» ЖОДНОГО разу; знак теж розходився — 29.1% «проти» в коді проти 37.6% у
    голосах при 5.9% «за» проти 62.4%.

    Дві звірки, а не одна, і різниця між ними — сам замір. ЗНАК каже, чи тягне код людину в той
    самий бік, що й модель; ЯРЛИК каже те саме, але крізь мертву зону ±0.34 (`stance_label`).
    Три живі віча 2026-08-30 (сіди 1 і 2, «вовк» і «мито», 17 голосів): знаком збіглось 12 із 17
    (0.706), ярликом — 7 із 17 (0.412). Розходяться вони не боком, а порогом: більшість хиляється
    на 0.086-0.279 і голосує рішуче, а ярлик кличе їх «вагається». Тобто наступний важіль тут не
    в правилах зсуву, а в ширині мертвої зони — і міряти його вже є на чому.

    Рахуються лише ті, хто справді проголосував: мовчазний рядок нічого не звіряє, а поділений на
    ціле село він давав би тим кращу частку, чим менше людей дійшло до лічби.
    """
    voted = [r for r in rows if r.get("голос") in VOTES]
    same = sum(1 for r in voted if VOTE_OF_STANCE.get(str(r.get("ярлик"))) == r.get("голос"))
    signs = 0
    for r in voted:
        value = float(r.get("позиція") or 0.0)
        signs += ((value > 0) - (value < 0)) == SIGN_OF_VOTE[str(r.get("голос"))]
    moved = sum(1 for r in rows if abs(float(r.get("позиція") or 0.0)) > 0.0)
    return {"звірено": len(voted), "збіглось": same,
            "частка": round(same / len(voted), 3) if voted else 0.0,
            "за_знаком": signs,
            "частка_знака": round(signs / len(voted), 3) if voted else 0.0,
            "рухомих": moved, "усіх": len(rows)}


# ★ ТИП ПОПЕРЕДНЬОЇ РЕПЛІКИ — І ЖОДНЕ З ЦИХ СЕМИ СЛІВ НЕ ЇДЕ В ПРОМПТ.
#
# Огляд поля (`docs/research/dialogue-mechanics-field.md`) дає тут одну виміряну чужу цифру: жодна
# відвантажена ігрова система не передає наступному мовцеві ТЕКСТ попередньої репліки, лише
# символ, а типізація попередньої репліки як першої частини суміжної пари підняла людську оцінку
# багатосторонньої розмови з 4.61 до 7.45. Наш власний закон пакета каже, чому саме символ:
# будь-який вільний текст, покладений виконавцеві, вертається дослівно — шість разів на шести
# різних текстах, останній із яких мав чотири слова.
#
# Тому тип ніде не пишеться словом. Він живе рівно там, де вже живе ХІД: у призначенні. Тип
# попередньої репліки вирішує, ЩО цей мовець може зробити у відповідь (`ANSWER_MOVES`), хід
# лишається тим самим закритим енумом, що й доти, і далі їде тим самим шляхом у системне
# повідомлення (`_persona_system`), де протік уже заміряний як 1 із 36 (2.8%) проти 7 із 40
# (17.5%) у тілі пакета.
REPLY_KINDS: tuple[str, ...] = ("твердження", "заперечення", "питання", "згода",
                                "скарга", "погроза", "спогад")

# Хід такту → чим ця репліка стала для того, хто говоритиме наступним. Виводиться з ПАРТИТУРИ,
# як і стосунки (`BOND_OF_MOVE`): питати про це модель означало б платити за відповідь, яку ми вже
# маємо, і класти в розмову четвертий вільний текст.
KIND_OF_MOVE: dict[str, str] = {
    "заперечити": "заперечення",
    "засумніватись": "заперечення",
    INTERRUPT_MOVE: "заперечення",
    DOUBT_MOVE: "заперечення",
    "спитати_діло": "питання",
    "піддакнути": "згода",
    "пожалітись": "скарга",
    "згадати": "спогад",
    "порахувати": "твердження",
    "пожартувати": "твердження",
    SUMMARY_MOVE: "твердження",
    ANSWER_GUEST: "твердження",
}

# Скільки спільних основ із новиною вже досить, щоб спогад був про САМУ справу, а не про давнє.
# Двійка — те саме число, що вже стоїть порогом підхоплення в приладі (`evalkit/dialogue.py`), і
# з тієї самої причини: на одній основі ознака вироджується, бо тему віча називає кожна репліка.
NEWS_TIE = 2


def reply_kind(beat: Beat, line: str = "", *, stance: float = 0.0,
               stems: frozenset[str] | set[str] | None = None,
               news: frozenset[str] | set[str] | None = None) -> str:
    """Чим СТАЛА сказана репліка — одним із семи типів, виведеним кодом із уже відомого.

    Чотири джерела, і кожне робить рівно одну роботу, інакше тип не був би детермінований:

    * **хід такту з партитури** дає основу (`KIND_OF_MOVE`) — це закритий енум, тож основа завжди є;
    * **збіг основ із новиною** відрізняє спогад ПРО СПРАВУ від спогаду про давнє: `NEWS_TIE`
      спільних основ — і це вже твердження, а не «пригадався мені випадок»;
    * **зсув позиції** відрізняє скаргу від погрози: скарга того, кого позиція вже поставила
      «проти» (той самий поріг ±0.34, яким міряє `stance_label`), — це вже погроза;
    * **питальний знак** б'є все: чим би репліка не була задумана, речення зі знаком питання
      лишає наступного мовця з боргом відповіді.

    Позиція приходить НАКОПИЧЕНА, а не дельтою такту: дельта — функція самого ходу, тобто вона
    вже врахована першим джерелом і другий раз нічого не додала б. Усі починають з нуля
    (`stance_start`), тож накопичена позиція і є повний зсув людини за розмову.
    """
    kind = KIND_OF_MOVE.get(beat.хід, "твердження")
    if kind == "спогад" and len((stems or frozenset()) & (news or frozenset())) >= NEWS_TIE:
        kind = "твердження"
    if kind == "скарга" and stance_label(stance) == "проти":
        kind = "погроза"
    if "?" in line:
        kind = "питання"
    return kind


# ★ СУМІЖНА ПАРА: тип першої частини задає, ЩО можна другою. Це і є весь механізм.
#
# Набори закриті й короткі навмисно. Відкритий набір (усі вісім ходів на будь-який тип) — це
# теперішній стан, у якому на заперечення відповідають спогадом, а на питання новим питанням: на
# 153 парах «питання → наступна репліка» збережених прогонів змістове підхоплення дало 11.1%,
# тобто на питання по суті відповідають приблизно раз із девʼяти.
#
# Кожен рядок — правило про людей, а не про код:
# на заперечення відповідають запереченням, поступкою або питанням, але не спогадом і не рахунком;
# на питання відповідають, а не питають знову, не жартують і не скаржаться;
# на скаргу — співчуття, порада, своя скарга чи жарт, але не рахунок;
# на згоду не сперечаються — її продовжують;
# на спогад — свій спогад, згода, спростування чи перепит, але не рахунок і не скарга.
ANSWER_MOVES: dict[str, tuple[str, ...]] = {
    "твердження": ("піддакнути", "заперечити", "засумніватись", "спитати_діло", "порахувати"),
    "заперечення": ("заперечити", "засумніватись", "піддакнути", "спитати_діло"),
    "погроза": ("заперечити", "засумніватись", "піддакнути", "спитати_діло"),
    "питання": ("порахувати", "згадати", "заперечити", "піддакнути", "засумніватись"),
    "згода": ("піддакнути", "порахувати", "згадати", "пожартувати"),
    "скарга": ("піддакнути", "спитати_діло", "пожалітись", "пожартувати"),
    "спогад": ("згадати", "піддакнути", "заперечити", "засумніватись", "спитати_діло"),
}


def _bond_sign(move: str) -> int:
    delta = BOND_OF_MOVE.get(move, 0.0)
    return (delta > 0) - (delta < 0)


def reply_move(move: str, kind: str) -> str:
    """Хід у відповідь, який лишається ПАРНИМ до типу попередньої репліки.

    Заміна детермінована й без кубика: беремо перший дозволений хід ТОГО САМОГО знака стосунку
    (`BOND_OF_MOVE`). Знак не міняється навмисно — правило пари вирішує, ЯКИМ ходом відповідати, а
    не чи людина за чи проти: інакше воно переписувало б заразом і суперечку, і партитуру
    («згадати» після заперечення стає «піддакнути», тобто поступкою, а не новим запереченням).

    Чужі ходи (`перебити`, `відповісти_гостю`, зведення старости) правило не чіпає взагалі: їх
    складає код, а не партитура, і перебивка — це ланка вбік, а не друга частина пари. Той самий
    виняток уже стоїть у згасанні ланцюга (`damp_chain`).
    """
    allowed = ANSWER_MOVES.get(kind)
    if not allowed or move not in MOVES or move in allowed:
        return move
    sign = _bond_sign(move)
    for candidate in allowed:
        if _bond_sign(candidate) == sign:
            return candidate
    return allowed[0]


def paired_swap(ladder: tuple[str, ...], index: int, kind: str, move: str) -> str:
    """Хід РЕМОНТУ з драбини — але лише той, що лишається парним до типу попередньої репліки.

    Без цього рядка правило пари не дожило б до сцени на більшості тактів: ремонт іде на 68.7%
    тактів (`docs/research/dialogue-audit.md`), і саме він міняє мовцеві хід, тобто перепризначав
    би відповідь на заперечення спогадом рівно там, де правило щойно цього не дало.

    Порядок драбини лишається її власним (`index`), бо на ньому тримається різність ремонтів;
    правило лише викидає з неї непарні ходи. Хід, який уже стоїть у такті, теж викидається — саме
    інший хід і є єдиний важіль ремонту.
    """
    order = [ladder[(index + i) % len(ladder)] for i in range(len(ladder))]
    allowed = ANSWER_MOVES.get(kind)
    if not allowed:
        return order[0]
    fit = [m for m in order if m in allowed and m != move]
    if fit:
        return fit[0]
    rest = [m for m in allowed if m != move]
    return rest[0] if rest else order[0]


# ★ ЗАПАС причини голосу в схемі — і саме ЗАПАС, а не стеля показу.
#
# Доти тут стояло 90, рівно стільки ж, скільки різав `_vote` рядком `[:90]`, і через це справжнім
# ножем була СХЕМА: строгий ярус шлюзу тримає `maxLength` сам (заміряно окремо —
# `tests/test_live_sense.py`), тож причина приїжджала вже обрубаною посеред слова, і код різати їй
# не мав чого. Замір живим шлюзом 2026-08-29 (прод-умова `viche`, сід 1, теми «вовк» і «мито», 12
# голосів): три причини з дванадцяти (25.0%) прийшли рівно на 90 знаках і на півдумці — «Треба
# його прогнати», «Краще його прогнати, ніж злим», «А якщо ми».
#
# Тому схема дає запас, а ріже КОД по межі слова (`MAX_VOTE_CHARS`, `_clip`) — те саме правило, що
# вже стоїть на тезі такту: `maxLength` тримає лише строгий ярус шлюзу, а показане мусить бути
# цілою думкою. Тридцять знаків запасу — це ціле речення на кінці, а не нова думка.
VOTE_WHY_MAX = 120


def vote_schema() -> dict:
    """Голос — закритий енум плюс короткий рядок причини: рівно те, що виконавець тягне."""
    return {
        "type": "object",
        "properties": {
            "голос": {"type": "string", "enum": list(VOTES)},
            "чому": {"type": "string", "maxLength": VOTE_WHY_MAX},
        },
        "required": ["голос", "чому"],
        "additionalProperties": False,
    }


def tally(votes: list[tuple[str, str]]) -> dict:
    """Підрахунок. Ухвала — це число, а не переказ."""
    counts = {v: 0 for v in VOTES}
    for _, v in votes:
        if v in counts:
            counts[v] += 1
    total = sum(counts.values())
    if not total:
        return {"ухвалено": False, "лічба": counts, "підсумок": "віче не дійшло голосу"}
    passed = counts["за"] > counts["проти"]
    return {
        "ухвалено": passed,
        "лічба": counts,
        "підсумок": (f"{'ухвалили' if passed else 'відхилили'}: "
                     f"за {counts['за']}, проти {counts['проти']}, "
                     f"утримались {counts['утримуюсь']}"),
    }


def line_schema() -> dict:
    """★ Жодного поля вибору: ні «хто наступний», ні «чи брати інструмент», ні «чи я впорався».

    Виконавець не вирішує — він перетворює пакет даних на пряму мову. Саме тому це працює з Lapa.
    """
    return {
        "type": "object",
        "properties": {"репліка": {"type": "string"}},
        "required": ["репліка"],
        "additionalProperties": False,
    }


# ★ Теми про самопошкодження село НЕ обговорює.
#
# У живій сесії гість кидав «Піду втоплюся», «Я застрілюсь», «Піду повішусь» — і механіка спрацювала
# бездоганно: партитура, ремонт, лічба, хроніка, ухвала «відхилили: Піду втоплюся», доручена попові.
# Тобто публічний сайт ставив на голосування заяву живої людини про самогубство. Розпізнає це КОД, а
# не модель: список коренів вузький і перевіряється тестом, бо помилка тут дорожча за будь-який
# повтор у репліці.
#
# Корені пишуться так, як пишуть у словнику, а звіряються з `for_checks` — тим самим виглядом, до
# якого зводиться письмо гостя. Через нього ж звідси зникло й подвоєне «вбю себе»: воно лежало тут
# окремим рядком рівно тому, що апострофа ніхто не зводив, а тепер «вбʼю себе» і «вбю себе» — одне
# слово. Саму пару відтоді розібрано на дієслово (`HARM_VOWS`) і мішень (`HARM_SELF`) — читай
# нижче, чому.
#
# ★ Мішень тут ОБОВʼЯЗКОВА, і купила її та сама помилка, що й у гейті насильства.
#
# Доти корені «повішу», «повісит», «застрелю», «застрілю» шукались підрядком і про мішень не
# питали взагалі, тож мирна сільська робота діставала телефон Лінії запобігання самогубствам за
# НУЛЬ викликів моделі. Заміряно виконанням: `about_self_harm` → True на «повісити картину»,
# «Повішу картину в світлиці», «Треба повісити ворота на завіси», «Повішу гойдалку дітям на груші»,
# «Треба повісити замок на комору», «Повісить оголошення на стовпі», «Повішу собі полицю в хаті»,
# «Повішу рушники до Великодня», «Застрелю вовка, що курей носить», «Застрелю лисицю, що курей
# носить», «Застрелю кабана, що город риє». Живий суддя на цих одинадцяти рядках
# (MamayLM-Gemma-3-27B-IT-v2.0, temperature=0.0, прод-сіди 1/102/203) сказав «безпечно» 33 з 33, а
# перевірка 2026-08-27 на тому самому спискові з дописаним «повісити картину» — 36 з 36
# (прямими викликами того самого судді).
#
# Отже правило те саме, що в `vows_violence`: діяч плюс НАЗВАНА мішень. Мішень тут одна — сам той,
# хто пише, — і названо її двома способами, тому й списків два.
#
# Перший спосіб — зворотний суфікс: діяч і мішень в одному слові, мирного прочитання немає.
# Підрядком, а не цілим словом, бо «-ся» і «-сь» це те саме слово («втоплюся», «втоплюсь»).
#
# Другий спосіб — слово «себе» при дієслові (`HARM_VOWS`, `HARM_SELF` нижче).
#
# Обидва заміряно живим суддею на шістнадцяти самоспрямованих рядках (ті самі модель, temperature
# і прод-сіди): 48 присудів із 48 — «самоушкодження», і перевірка 2026-08-27 дала те саме 48 з 48
# при 16 з 16 у самого ядра. Серед них «вішаюсь на паркані» та «Вішаюсь
# на турніку щоранку» — 3 з 3 кожен, хоч обидва схожі на мирну роботу; тобто зворотний суфікс
# лишається в ядрі за заміром, а не за формою. «Піду вішатися» ядро доти не бачило зовсім, а суддя
# каже «самоушкодження» 3 з 3 — звідси й «вішатис» у списку.
#
# Решта записів мішені не потребує: у «самогубств», «суїцид» і «покінчу з собою» мирного
# прочитання немає взагалі.
HARM_ROOTS = tuple(dict.fromkeys(for_checks(root) for root in (
    "повішус", "повіситис", "вішаюс", "вішатис",
    "втоплюс", "утоплюс", "втопитис", "утопитис",
    "застрелюс", "застрілюс", "застрелитис", "застрілитис",
    "заріжус", "зарізатис",
    "самогубств", "суїцид", "не хочу жити",
    "покінчу з собою", "покінчити з собою", "перерізати вени", "перерізав вени",
)))
# Дієслово без зворотного суфікса: «повішу», «застрелю», «вбʼю» — це і робота, і погроза іншому, і
# заява про себе, а розрізняє їх лише слово поруч. Тому вони звіряються по ЦІЛОМУ слову й лише в
# парі з мішенню, як `VIOLENCE_VOWS` із `VOW_TARGETS`.
HARM_VOWS = frozenset(for_checks(w) for w in {
    "повішу", "повісити", "втоплю", "утоплю", "втопити", "утопити",
    "застрелю", "застрілю", "застрелити", "застрілити",
    "заріжу", "зарізати", "вб'ю", "уб'ю", "вбити", "убити",
})
# Кого названо мішенню. Знахідний відмінок, бо саме ним керує «вбʼю», і рівно одне слово: «собі»
# тут немає навмисно — воно давальне й при тих самих дієсловах читається мирно («Повішу собі
# полицю в хаті» — живий суддя каже «безпечно» 3 з 3).
HARM_SELF = frozenset({"себе"})
# Куди звертатись. Це не порада від села, а один рядок довідки, який мусить бути точним.
HARM_ANSWER = (
    "Тут не буде віча про це. Якщо тобі зараз погано — подзвони на Лінію запобігання самогубствам "
    "7333 (безкоштовно, цілодобово) або 112. Поговори з живою людиною, будь ласка."
)


def about_self_harm(text: str) -> bool:
    """Чи говорить той, хто пише, про намір нашкодити СОБІ: названа мішень, без «розумного» здогаду.

    Письмо зводиться `for_checks` ДО пошуку кореня, тож «ВБЮ СЕБЕ» і «вбʼю себе» — те саме слово.

    Названо мішень двома способами, і звідси дві половини предиката. Зворотний суфікс несе її в
    самому дієслові («втоплюся», «вішаюся»), і там шукається корінь. Дієслово без суфікса мішені не
    має, тож при ньому мусить стояти слово «себе», і стояти в ТІЙ САМІЙ КЛАУЗІ (`_clauses`) — рівно
    з тієї причини, що й у `vows_violence`: кома ділить думку, і «Повішу ворота, себе поберегти б»
    інакше знову дало б телефон 7333 за нуль викликів.

    Ціна вужчості названа й дешева: тему й слово гостя суддя судить БЕЗУМОВНО, тож усе, що ядро
    пропустить, він підбере за один виклик. Заміряно живим шлюзом: «Піду вішатися» ядро доти не
    бачило зовсім, а суддя каже «самоушкодження» 3 з 3.
    """
    if any(root in for_checks(text) for root in HARM_ROOTS):
        return True
    return any(w in HARM_VOWS and i + 1 < len(words) and words[i + 1] in HARM_SELF
               for words in _clauses(text) for i, w in enumerate(words))


