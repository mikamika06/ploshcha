# «безпечно» (MamayLM-Gemma-3-27B-IT-v2.0, temperature=0.0, прод-сіди 1/102/203): 8 рядків × 3
# сіди — 24 присуди з 24.
#
# Знаки тут ті, що ділять речення на думки: кома, крапка з комою, двокрапка, крапка, знак оклику,
# знак питання, три крапки й тире. Переносу рядка серед них немає навмисно — він ділить раніше,
# самим рядком, бо зведення письма зводить усякий пропуск до пробілу.
CLAUSE_BREAKS = frozenset(",;:.!?…—–")


def _splits_a_clause(plain: str, i: int) -> bool:
    """Чи ділить думку знак на місці `i`: розділовий — завжди, дефіс — лише окремим знаком.

    Дефіс української стоїть УСЕРЕДИНІ слова («з-під», «сякий-такий», «будь-хто»), тож межею він
    рахується тільки там, де ним набрали тире, — коли з котрогось боку від нього не літера.
    """
    ch = plain[i]
    if ch in CLAUSE_BREAKS:
        return True
    return ch == "-" and not (i and plain[i - 1].isalpha()
                              and i + 1 < len(plain) and plain[i + 1].isalpha())


def _clauses(text: str) -> list[list[str]]:
    """Слова по КЛАУЗАХ: той самий один вигляд письма, але межа думки в ньому збережена.

    Ділити треба саме тут, а не в кожному гейті окремо: `for_checks` зводить письмо, а розділовий
    знак після нього однаково зникав би разом із рештою нелітер. Порожні клаузи не вертаються —
    «...» і «?!?!» дають нуль списків, а не нуль слів у списку.

    Рядки діляться ДО зведення письма, бо `for_checks` зводить усякий пропуск до пробілу: після
    нього переносу вже немає, а гість, який набрав тему в три рядки, поставив три межі. Через це й
    письмо рахується по рядку: тема, у якій один рядок кирилицею, а другий суцільно латиницею, —
    це два написання, а не один мішаний рядок, тож «vbyu susida» другим рядком читається так само,
    як і однією темою. Латинське слово ВСЕРЕДИНІ кириличного рядка це не чіпає: там рядок
    мішаний, і «GitHub» лишається «GitHub».
    """
    out: list[list[str]] = []
    for row in (text or "").splitlines():
        plain = for_checks(row)
        marked = "".join(ch if ch.isalpha() else "\n" if _splits_a_clause(plain, i) else " "
                         for i, ch in enumerate(plain))
        out += [words for part in marked.split("\n") if (words := part.split())]
    return out


def _plain_words(text: str) -> list[str]:
    """Слова в одному вигляді: `for_checks` зводить регістр, апостроф, двійники й латиницю.

    Це ЄДИНИЙ вхід у всі списки цього файлу, тож нормалізувати треба саме тут: гість пише «бʼє»,
    «б’є», «бє» і «бье», латинську «i» в «чоловiк» і цілу тему латиницею — а списки написані одним
    правописом. Апостроф після зведення зникає зовсім, тому в слові його вже не тримаємо.

    Межу клаузи цей вигляд НАВМИСНО забуває, бо ним живе широка смуга, а смуга вироку не ухвалює:
    її хибне спрацювання коштує одного дешевого виклику, а пропуск — продукту. Хто судить сам
    (`vows_violence`), бере слова клаузами (`_clauses`), і там межа обовʼязкова.
    """
    return [w for clause in _clauses(text) for w in clause]


def _beaten_by_a_force(words: list[str], i: int) -> bool:
    """Чи бʼє тут стихія або хвороба, а не людина: «град побив», «мороз побив», «мене бʼє дрож»."""
    near = words[max(0, i - VIOLENCE_FORCE_SPAN):i + VIOLENCE_FORCE_SPAN + 1]
    return any(n in VIOLENCE_FORCES for n in near)


def _a_place_not_a_person(words: list[str], j: int) -> bool:
    """Чи це «у нас»/«в вас» — тобто село, а не мішень: «побив у нас пшеницю»."""
    return words[j] in VIOLENCE_PLACE_PRONOUNS and j > 0 and words[j - 1] in VIOLENCE_PLACE_PREPS


def about_violence(text: str) -> bool:
    """Чи це про насильство над іншим: побиття, погроза вбити чи скалічити, загроза дитині.

    Трійка, а не корінь і навіть не пара. Самі дієслова мирні («бʼє джерело», «бити масло»,
    «побив глек», «вбʼю цвях у стіну»), сама пара теж: у «Град побив у нас усю пшеницю» є і
    дієслово, і «нас», а насильства нема. Тому питаємо ще й про діяча — стихія й хвороба бʼють
    не людину, — а «нас» після прийменника читаємо як місце. Здогаду тут немає, списки закриті.
    """
    words = _plain_words(text)
    for i, w in enumerate(words):
        if w not in VIOLENCE_VERBS:
            continue
        if _beaten_by_a_force(words, i):
            continue
        start = max(0, i - VIOLENCE_SPAN)
        for j in range(start, min(len(words), i + VIOLENCE_SPAN + 1)):
            if words[j] in VIOLENCE_TARGETS and not _a_place_not_a_person(words, j):
                return True
    return False


# ★ Тверде ядро гейта насильства: те, чого розуміти не треба.
#
# Присуд змісту тепер ухвалює суддя (`SENSE_HANDOVER`), і це коштує виклику, латентності й
# залежності від шлюзу. Обіцянка «вбʼю сусіда» нічого з цього не варта: діяча названо самою формою
# дієслова — перша особа однини майбутнього, — а мішень названо словом, яке означає ЛЮДИНУ, і
# більше в реченні розуміти нема чого. Тому вона й далі закривається кодом, за нуль токенів, і
# жоден збій каналу цього не змінює.
#
# ★ Голий займенник мішенню не рахується, і це не смак, а замір у прод-умові (`build_viche`,
# справжній шлюз, MamayLM-Gemma-3-27B-IT-v2.0): «Кабан уже здоровий, заріжу його до Різдва»,
# «Цвях кривий, прибʼю його з другого боку» і «Кріт город риє, прибʼю його лопатою» діставали
# `viche_violence` і рядок із телефоном домашнього насильства 1547 при НУЛІ викликів моделі й нулі
# токенів. Причина та сама, що й у «побив» зі смуги вище: «його» саме по собі не людина — воно
# кабан, гусак, півень, курка, тхір, цвях або кріт, — і дізнатись це можна лише з речення. Живий
# суддя на восьми таких рядках (temperature=0.0, сіди 1/102/203) сказав «безпечно» 24 рази з 24, а
# на «Вбʼю його, як прийде до хати» — «насильство_над_іншим» 3 з 3. Тобто займенник не пропущено:
# його присуд просто коштує виклику, як і решта двозначного.
#
# Мішень тут і далі обовʼязкова, бо саме нею ядро відрізняється від смуги: «вбʼю цвях у стіну» і
# «заріжу кабана до Різдва» — робота, а не погроза. Змінилось те, ЩО нею рахується.
VIOLENCE_VOWS = frozenset(for_checks(w) for w in {
    "вб'ю", "уб'ю", "приб'ю", "заріжу", "задушу", "покалічу", "скалічу",
})
# Кого обіцяють скалічити: знахідний відмінок, бо саме ним керує «вбʼю». Три родини слів, і всі
# закриті — рідня й свояки, сусід та інша людина взагалі, роль цього села (`GENDER_BY_ROLE`:
# коваль, мірошник, парубок, піп, староста, чумак, дяк, шептуха, шинкарка, мати, дівчина, дід).
# Роль тут не окраса: «Заріжу коваля» і «Вбʼю сусіда, як ще раз пустить худобу» доти платили по
# два виклики судді (1094 і 1117 токенів у прод-умові ТОГО кругу; після того, як `SENSE_SYSTEM`
# доріс, ті самі два виклики коштують 1364-1392 — замір 2026-08-27) за присуд, який видно з самої
# форми.
#
# ★ Склад переглянуто ЗАМІРОМ, а не смаком, і викинути з нього не довелось нічого.
#
# Питання складу одне: чи є в цього слова мирне прочитання, коли воно стоїть просто при дієслові.
# Живий суддя відповів на кожному записі окремо (рядок «Заріжу X», MamayLM-Gemma-3-27B-IT-v2.0,
# temperature=0.0, прод-сіди 1/102/203): 38 мішеней × 3 сіди — 114 присудів, і «безпечно» серед
# них немає ЖОДНОГО. Двадцять вісім записів дали «насильство_над_іншим» 3 з 3, а десять близької
# рідні («сина», «дитину», «дружину», «маму», «батька», «сестру», «онука», «дітей», «доньку»,
# «дочку») — «самоушкодження» 3 з 3, тобто суддя читає погрозу власній родині як шкоду собі й дав
# би гостю телефон 7333 замість 102 і 1547. Саме тому рідня тут і лишається: ядро віддає її
# правильному номеру за нуль токенів.
#
# Отже мирне ловилось не складом цього списку, а зниклою межею клаузи (`_clauses`), і лагодиться
# саме вона.
VOW_TARGETS = frozenset({
    "дитину", "дітей", "сина", "доньку", "дочку", "дружину", "жінку", "чоловіка", "матір",
    "маму", "батька", "брата", "сестру", "онука", "діда", "бабу",
    "сусіда", "сусідку", "кума", "куму", "дядька", "тітку", "хлопця", "дівчину", "людину",
    "коваля", "мірошника", "парубка", "попа", "отця", "старосту", "чумака", "дяка", "шептуху",
    "шинкарку", "шинкаря", "пастуха", "писаря",
})


def vows_violence(text: str) -> bool:
    """Чи обіцяє той, хто пише, скалічити людину: перша особа майбутнього плюс названа мішень.

    Про діяча тут не питають — його названо формою дієслова. Питають лише про мішень, і вона мусить
    стояти ПРИ дієслові, а не у вікні `VIOLENCE_SPAN`, як у смузі. Причина в самій мові: у
    чоловічого роду знахідний збігається з родовим, тож у вікні трьох слів «Для сина заріжу
    кабана» читалось би як погроза синові. Сусіднє слово такої омонімії не має: «заріжу кабана» —
    робота, «заріжу коваля» — погроза, і третього тлумачення в них немає.

    Через це ядро тепер вужче з обох боків: «Вбʼю того клятого коваля» і «Сусіда вбʼю, як ще раз
    пустить худобу» йдуть до судді. Ухил навмисний і той самий, що в усьому цьому гейті: пропуск
    коштує одного виклику, після якого віче однаково закривається, а хибне закриття коштує теми.

    ★ «При дієслові» означає в ТІЙ САМІЙ КЛАУЗІ, і без цього все попереднє не варте нічого.
    Слова доти бралися пласким списком, тож розділовий знак важив стільки ж, скільки пробіл, і
    «сусіднє слово» після коми бралось уже з наступної думки: «Кабана на Різдво заріжу, кума
    покличу на ковбаси» давало пару «заріжу кума», тобто мирна сільська тема діставала телефон
    домашнього насильства 1547 за нуль викликів моделі. Живий суддя на восьми таких рядках сказав
    «безпечно» 24 рази з 24 (три прод-сіди на рядок).

    Ціна межі теж названа: те, що ядро через неї пропустить, підбирає суддя, якого тема кличе
    безумовно (`Viche._topic`). Заміряно живим шлюзом на трьох рядках, яких ядро не бачить зовсім
    («Приріжу сусіда», «Голову скручу сусідові», «Ноги переламаю сусідові»): 9 присудів із 9 —
    «насильство_над_іншим».
    """
    return any(w in VIOLENCE_VOWS and i + 1 < len(words) and words[i + 1] in VOW_TARGETS
               for words in _clauses(text) for i, w in enumerate(words))


# ★ Названа людина плюс злочин — це вже не поголос, а вирок.
#
# `_emit_rumour` за побудовою пропускає твердження САМЕ ТОДІ, коли підстави не було (це й означає
# «чутка»), а єдина перевірка щодо імені там була на повний збіг УСЬОГО тексту з іменем чи роллю.
# Тому «Одарка вкрала гроші» проходило цілим: осідало в базі села назавжди, верталось у наступну
# партитуру й вилазило на Дошку окремою темою. Те саме через ухвалу: лічба голосів робила зі
# звинувачення рішення села з підписом виконавця й місцем на сцені.
#
# Самого кореня замало: «у селі крадії» — поголос без адресата, і він мусить ходити далі. Самого
# імені теж: «Одарка привезла сіль» — новина. Але й пари замало, і це коштувало селу ухвал —
# читай нижче, при `ACCUSE_ROOTS`: потрібен ДІЯЧ, а не сусідство.
#
# Корені короткі й однозначні: кожен трапляється лише в словах про злочин. Коротшати їм нікуди —
# «зрад» узяв би й «зрадів», а це радість, тому стоять довші «зрадив», «зрадниц».
CRIME_ROOTS = (
    "крад", "крал", "крав", "злоді",
    "вбив", "убив", "заріза", "підпал", "отруї", "згвалт", "зґвалт",
    "зрадив", "зрадил", "зрадник", "зрадниц", "шахра", "хабар",
)
# Коротші за це на імена не звіряємось: гість підписаний «ти», і з нього вийшла б основа в одну
# літеру, яка збігається з половиною слів у реченні.
MIN_NAME_STEM = 3


def _name_stem(word: str) -> str:
    """Основа імені без закінчення: «Одарка», «Одарки», «Одарку», «Одаркою» — одна людина.

    Кінцеві голосні відкидаємо, а кінцеве «ц» зводимо до «к», бо в місцевому відмінку «Одарка» стає
    «Одарці»: без цього та сама людина в іншому відмінку читалась би як чужа.
    """
    stem = word.rstrip("аеєиіїоуюяь'")
    return stem[:-1] + "к" if stem.endswith("ц") else stem


# ★ Вироком робить ДІЯЧ, а не сусідство імені зі словом про злочин — а хто діяч, каже суддя.
#
# Усе, що написано нижче про відмінок і сусідство, лишається на місці й лишається правдою про сам
# механізм; неправдою було б лишити на місці його ПРИЗНАЧЕННЯ. Розрізнення діяча цей код не
# тримає: заміряно виконанням, що він рахує вироком трьох невинних («Марія злодіїв не бачила»,
# «Одарка злодіїв боїться і замикає хату», «Дід Свирид злодіїв прогнав з городу»), а «у Одарки
# вкрали козу» пропускає — правильно, але з тієї самої випадковості відмінка. Тепер це вирок лише
# при закритому шві й економія при відкритому: `_beside`, `ACCUSE_FILLERS` і `ACCUSE_SPAN` не
# розрізняють діяча, а лише не дають платити за очевидне.
#
# Пари «імʼя + корінь» замало, і це заміряно: на складі села вона рахувала вироком чотири рядки з
# чотирьох, де названа людина — потерпіла або свідок. «У Одарки вкрали козу», «в баби Горпини
# вночі вкрали курей», «Іван бачив, як хтось підпалив стерню», «Марія боїться, що в селі завелись
# злодії». Ціна помилки не абстрактна: саме на такій темі село проголосувало, а ухвала зникла.
#
# Розрізняє ВІДМІНОК, і не вгаданий за закінченням, а взятий зі списку людей: там кожен записаний
# так, як його звати. Діяч стоїть у називному («Одарка вкрала», «Іван підпалив»), а той, у кого
# вкрали, і той, кому приписують, — у непрямому («у Одарки», «Одарці»). Тому й правил два, і вони
# дзеркальні:
#
# 1. Називне імʼя ПРИ самому злочинному слові — вирок: «Одарка вкрала», «козу вкрала Одарка».
# 2. Непряме імʼя при обвинувальному дієслові плюс сам злочин поруч — теж вирок: «Одарці
#    приписують крадіжку», «Івана підозрюють у підпалі». Називне тут навпаки рятує: «Одарка
#    звинувачує сусіда» — це вона обвинувачує, а не її.
#
# «При» означає сусіднє слово, а не вікно: свідка рятує саме відстань — у «Іван бачив, як хтось
# підпалив» злочин стоїть при чужому дієслові. Наскрізь пропускаються лише часові та підсилювальні
# вставки, бо діяча вони не міняють («Одарка вночі вкрала»).
ACCUSE_ROOTS = ("припису", "приписа", "звинувач", "обвинувач", "винуват", "підозр", "запідозр")
# Скільки слів між обвинувальним дієсловом і самим злочином: «звинувачують у крадіжці громадських
# грошей» — три.
ACCUSE_SPAN = 4
# Що може стояти між людиною та її дієсловом, не міняючи, хто діяч. Список закритий, як і решта
# тутешніх: здогаду тут немає.
ACCUSE_FILLERS = frozenset({
    "вночі", "опівночі", "вранці", "удень", "вдень", "увечері", "ввечері",
    "вчора", "учора", "позавчора", "сьогодні", "давно", "колись", "щойно",
    "знову", "знов", "таки", "вже", "ще", "теж", "також", "нібито", "ніби",
    "сам", "сама", "самі", "потай", "тихцем",
})


def _people_forms(people: set[str]) -> tuple[set[str], set[str]]:
    """Дві множини з одного списку: основи (будь-який відмінок) і ДОСЛІВНІ називні форми.

    Називний відмінок не вгадується за закінченням, а береться зі списку людей — там кожен
    записаний так, як його звати. Інакше «Івана» читалось би як називне жіноче імʼя, і потерпілий
    («злодії обікрали Івана») став би діячем.

    Багатослівні підписи («дід Свирид», «баба Горпина») рахуються по кожному слову окремо: у
    репліці людину кличуть і одним словом.
    """
    stems, nominative = set(), set()
    for person in people:
        for w in _plain_words(str(person)):
            stem = _name_stem(w)
            if len(stem) >= MIN_NAME_STEM:
                stems.add(stem)
                nominative.add(w)
    return stems, nominative


def _beside(words: list[str], i: int, step: int) -> int:
    """Сусіднє слово при імені; -1, коли його немає. Часові вставки прозорі, діяча вони не міняють."""
    j = i + step
    while 0 <= j < len(words) and words[j] in ACCUSE_FILLERS:
        j += step
    return j if 0 <= j < len(words) else -1


def _a_crime(word: str) -> bool:
    return any(root in word for root in CRIME_ROOTS)


def _an_accusing_verb(word: str) -> bool:
    return any(word.startswith(root) for root in ACCUSE_ROOTS)


def about_accusation(text: str, people: set[str]) -> bool:
    """Чи називає це конкретну людину цього села ДІЯЧЕМ злочину — так, як це видно ЗІ СПИСКУ.

    `people` — імена й ролі, які в цьому селі означають людину: імена породженого села, склад віча
    і сталі персони.

    ★ Роль цієї функції змінилась, і назвати це треба чесно. Розрізняти діяча вона більше не
    мусить — і не могла: заміряно виконанням, що вона рахує вироком «Марія злодіїв не бачила»,
    «Одарка злодіїв боїться і замикає хату» та «Дід Свирид злодіїв прогнав з городу», бо відмінок
    і сусідство не кажуть, ХТО зробив. Тепер це дві інші, дешевші речі: поки шов судді закритий
    (`sense=False`), вона лишається вироком — дослівно тією поведінкою, що була, разом з усіма її
    заміряними тестами; коли відкритий — доданком широкої смуги (`maybe_accusation`), тобто
    гарантією, що жоден рядок, який ловив старий гейт, не пройде повз суддю мовчки.
    """
    words = _plain_words(text)
    stems, nominative = _people_forms(people)
    for i, w in enumerate(words):
        if _name_stem(w) not in stems:
            continue
        for step in (1, -1):
            j = _beside(words, i, step)
            if j < 0:
                continue
            if w in nominative:
                if _a_crime(words[j]):
                    return True
            elif _an_accusing_verb(words[j]) and any(
                    _a_crime(x) for x in words[max(0, j - ACCUSE_SPAN):j + ACCUSE_SPAN + 1]):
                return True
    return False


