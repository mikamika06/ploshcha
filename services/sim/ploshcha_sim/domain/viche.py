# ★ Образа у ВИВОДІ — єдине, що тут судиться: слово, а не тема, не людина й не погляд.
#
# Доти запобіжником було саме прохання в `LINE_SYSTEM` («живою розмовною, тільки пряма мова»), а
# прохання — інструкція, не гейт: увесь цей файл побудований на тому, що виконавець тримає схему й
# переступає прозу. Тому перелік ДОСЛІВНИЙ і закритий: лайка та ярлики, якими людину називають
# нелюдиною. Різкість не чіпається взагалі — «гребля тече третій рік, а староста бреше» проходить
# цілим, і на це стоїть окремий тест.
#
# Корінь звіряється як ПОЧАТОК слова, а не підрядок, і це не смак, а замір по 1 358 603 словах
# цього репозиторію: підрядком «хує» ловилось у «рахує» 94 рази, «блят» у «роблять» 32, «хуй» у
# «порахуй» 9, «дебіл» у «здебільшого» 6, «йоб» у «найобʼєктивніша». Початком слова на тому самому
# тексті — жодного хибного влучення. Ціна — форми з приростом («заїбись», «виблядок»): вони або
# стоять тут дослівно, як «довбойоб», або не ловляться зовсім, і це чесніше, ніж бракувати «рахує».
#
# ★ Тут лишились тільки ті корені, які означають ЛЮДИНУ й нічого більше.
#
# Омоніми звідси винесені в `SLUR_DOUBTFUL`, і це теж замір, а не смак. Заміряно живим прогоном у
# прод-умові на темі «Кухонні покидьки треба зносити свиням, а не в яр»: `viche_slur:sheptu` і
# `viche_slur_cut:divchyna`, тобто ніж різав сільську розмову про відходи. Причина та сама, що й у
# решті цього файлу: «покидьки» це і відходи, і образа; «падло» — стерво в яру; «бидло» — робоча
# худоба; «тварюка» — звірина. Слово одне, а вжите воно або про річ, або про людину, і розрізнити
# це можна тільки прочитавши речення — списком не можна в принципі.
#
# Ті, що лишились, сільського значення не мають узагалі, тож їх і далі ріже ніж без моделі: за
# «падлюку» й «мудака» ніхто не платить виклику, і жоден збій шлюзу їх не пропустить.
#
# Чого тут навмисно НЕМА: «сука» (поруч живуть «сучка» й «сукня»), «дурень» і «дурне діло» — це
# різка мова, а не ярлик.
SLUR_ROOTS = (
    "бляд", "блят", "хуй", "хує", "хуї", "хуя", "пізд", "пизд", "їб", "єб", "йоб", "довбойоб",
    "курв", "мудак", "мудил", "гандон", "гондон", "гівнюк",
    "мраз", "сволот", "падлюк", "виродок", "виродк",
    "дебіл", "ідіот", "кретин", "придурок", "придурк",
)


def about_slur(text: str) -> bool:
    """Чи є в тексті дослівна лайка — така, що людиною її називають ЗАВЖДИ.

    Механічно й тільки по слову: ані теми, ані наміру, ані людини тут не судять — на відміну від
    `about_accusation`, якому потрібна ПАРА «імʼя + злочин», образу видно з самого слова. На слова
    текст ріже той самий `_plain_words`, що й сусідні гейти, тож розділові знаки й великі літери
    нічого не ховають.

    Двозначного слова тут немає жодного: те, що в селі означає річ або худобу («покидьки», «падло»,
    «бидло», «стерво», «свиня»), лежить у `SLUR_DOUBTFUL` і вироку більше не ухвалює.
    """
    return any(w.startswith(root) for w in _plain_words(text) for root in SLUR_ROOTS)


