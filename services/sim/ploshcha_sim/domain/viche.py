def maybe_self_harm(text: str) -> bool:
    """Чи є привід питати суддю про самопошкодження: корінь без перевірки особи.

    Хибно ловить «втопив відро в криниці» — і добре: це один виклик, а не мовчання села про
    людину, яка пише, що з собою щось зробить.
    """
    low = for_checks(text)
    return about_self_harm(text) or any(hint in low for hint in HARM_HINTS)


def _a_violent_word(word: str) -> bool:
    return word in VIOLENCE_VERBS or any(word.startswith(root) for root in VIOLENCE_HINTS)


def maybe_violence(text: str) -> bool:
    """Чи є привід питати суддю про насильство: саме дієслово, без мішені й без вікна.

    Діяча тут НЕ питаємо як правильність, а лише як економію: коли при дієслові стоїть стихія чи
    хвороба («Град побив у нас усю пшеницю», «мене бʼє дрож»), питати нема про що й платити нема за
    що. Звірина у `VIOLENCE_FORCES` не лежить навмисно — саме через корову цей круг і почався.

    Старий гейт стоїть доданком, хоч за нинішніх списків він і так підмножина: саме ця стрічка
    тримає надмножину тоді, коли списки розійдуться, — а розійтись їм ще доведеться.
    """
    if about_violence(text):
        return True
    words = _plain_words(text)
    return any(_a_violent_word(w) and not _beaten_by_a_force(words, i)
               for i, w in enumerate(words))


def maybe_accusation(text: str, people: set[str]) -> bool:
    """Чи є привід питати суддю про вирок названій людині: імʼя й злочин будь-де в рядку.

    Ані відмінка, ані сусідства, ані `ACCUSE_FILLERS`, ані `ACCUSE_SPAN`: саме ця пара ловить усі
    три заміряні хибні спрацювання («Одарка злодіїв боїться і замикає хату», «Марія злодіїв не
    бачила», «Дід Свирид злодіїв прогнав з городу»), і тепер вони платять по одному виклику
    замість того, щоб діставати відмову від села.

    Старий гейт стоїть доданком із тієї самої причини, що й у насильстві: він гарантує надмножину
    й тоді, коли `CRIME_HINTS` перестане покривати `CRIME_ROOTS`.

    ★ Побиття — теж злочин, і смуга його не бачила.

    `CRIME_HINTS` названо словами про майно, зраду й хабар, тож «Одарка побила сусідську дитину»
    давало імʼя без злочину (заміряно виконанням: `maybe_accusation` → False). Наслідок за
    побудовою: чутка й ухвала звіряються саме цим предикатом (`Viche._accuses`), тобто вирок
    названій людині осідав у ПОСТІЙНОМУ стані села, не заплативши й не спитавши. Присуд при цьому
    БУВ — його ніхто не питав: живий суддя (MamayLM-Gemma-3-27B-IT-v2.0, temperature=0.0, сіди
    1/102/203) сказав «насильство_над_іншим» 3 з 3 на «Одарка побила сусідську дитину» і
    «звинувачення_особи» 3 з 3 на «Кажуть, Одарка побиває дітей». Сам `SENSE_SYSTEM` називає
    побиття злочином від першого круга — бракувало не тексту, а спискові.

    Дієслова беруться зі списку насильства, а не переписуються сюди коренями, і це замір, а не
    смак: підрядком «бив» ловить «зробив» і «бивень», «бил» — «зробили» й «кобилянську» (числа
    при `VIOLENCE_HINTS`), тобто кожне мирне речення з іменем платило б за виклик. Закритий
    перелік слів такого не робить.

    `_beaten_by_a_force` лишається тією самою ЕКОНОМІЄЮ, що й у насильстві: «Одарка каже, що град
    побив пшеницю» не коштує нічого, і це теж заміряно живим суддею — «безпечно» 3 з 3, тобто
    виклик там і справді був би викинутий.
    """
    if about_accusation(text, people):
        return True
    words = _plain_words(text)
    stems, _ = _people_forms(people)
    named = any(_name_stem(w) in stems for w in words)
    return named and any(any(root in w for root in CRIME_HINTS)
                         or (_a_violent_word(w) and not _beaten_by_a_force(words, i))
                         for i, w in enumerate(words))


def maybe_slur(text: str) -> bool:
    """Чи є привід придивитись до слова: тверда лайка або омонім, який у селі означає річ.

    Тверда лайка стоїть доданком не заради ціни (за неї виклику однаково не платять — ніж ріже її
    раніше), а заради тієї самої властивості, що й у сусідів: смуга мусить лишатись НАДМНОЖИНОЮ
    старого гейта й тоді, коли переліки розійдуться.
    """
    return about_slur(text) or any(w.startswith(root)
                                   for w in _plain_words(text) for root in SLUR_DOUBTFUL)


def suspect(text: str, people: set[str]) -> str | None:
    """Яка смуга змусила платити за виклик судді — або `None`, коли платити нема за що.

    Порядок той самий, що в гейтах віча: самоспрямоване перше, бо «застрелюся» і «вбʼю себе» мусять
    вести на 7333, а не на 102. Ім'я смуги лишається в інциденті: без нього не видно, ЩО саме
    коштувало прогонові токенів.

    Письмо гість зводить не сам, і смуга цього не помічає: усі чотири предикати нижче ходять у
    списки через `_plain_words` і `for_checks`, тобто бачать один вигляд слова замість пʼяти. Що
    це купило, заміряно на живому корпусі з 74 тем: смуга заговорила на 9 темах, де мовчала
    (35 небезпечних із 42 проти 27 доти), і не заговорила на жодній мирній понад ті 4, що чіпала
    й доти.
    """
    if maybe_self_harm(text):
        return "harm"
    if maybe_violence(text):
        return "violence"
    if maybe_accusation(text, people):
        return "accusation"
    if maybe_slur(text):
        return "slur"
    return None


def frame_schema() -> dict:
    """Що взагалі кинули на Дошку — одним реченням, від імені села.

    Коли тема беззмістовна («галя де», «Ало», «Хто я»), модель не каже «не розумію»: вона добудовує
    правдоподібну сільську подію й веде повноцінне віче навколо вигадки. У живих прогонах з «Пішов
    нафіг» вийшло «зникнення Янка-касира з грішми», з «Де я» — «відібрання землі та нові податки».
    Дешевий окремий виклик робить це чесно: він НЕ вигадує події, а переказує, що саме гість написав
    і на що це схоже, а далі село говорить уже про це.
    """
    return {
        "type": "object",
        "properties": {
            "зрозуміло": {"type": "boolean"},
            "про_що": {"type": "string", "maxLength": 160},
        },
        "required": ["зрозуміло", "про_що"],
        "additionalProperties": False,
    }


# Скільки варіантів репліки просити одним викликом.
LINE_CHOICES = 3


def lines_schema(n: int = LINE_CHOICES) -> dict:
    """★ Три варіанти репліки за ОДИН виклик — і вибирає з них код.

    Замір на живому шлюзі: поодинокий виклик дає «Та…» у 100% випадків (частки, penalty і
    температура на цьому шлюзі не працюють — вивід не мінявся зовсім). Але коли в тому самому
    виклику просиш три варіанти, модель сама починає їх по-різному: «Та що там…», «А що, як…»,
    «Краще б…» — однакових зачинів усередині виклику НУЛЬ на восьми пробах.

    Вибір лишається кодом: беремо той варіант, яким цього віча ще не заходили. Виконавець і далі
    нічого не вирішує — він лише дає матеріал.

    ★ ХОДУ ТУТ НЕМАЄ, І ЦЕ ЗАМІР, А НЕ НЕДОГЛЯД.

    Спроба провезти хід схемою — окреме поле `хід` з енумом на одне значення, поставлене ПЕРЕД
    `реплікою`, щоб виконавець отримав хід граматикою виводу, — перевірена живим шлюзом
    2026-08-29 (прод-умова `viche`, сід 1, теми «вовк» і «мито», 40 сказаних тактів) і ВІДКИНУТА:
    репліка стала називати хід замість того, щоб його робити, у 20 випадках із 40 (50.0%) проти
    7 із 40 (17.5%) доти. Дослівно: «спитати_діло», «перебити», «Порахувати, що вовка бачили»,
    «Згадати, як торік…», «Піддакую, пане писарю». Причина видна із самої форми: енум — це слово,
    яке модель мусить ВИПИСАТИ, а вже написане слово вона підхоплює наступним рядком. Відбір із
    трьох варіантів тут не рятує, бо хід стоїть у власному виводі кожного з них.

    Хід їде системним повідомленням персони (`Viche._persona_system`) — там він теж міряний, і
    там 3 із 35 (8.6%).
    """
    return {
        "type": "object",
        "properties": {"варіанти": {"type": "array", "minItems": n, "maxItems": n,
                                    "items": {"type": "string"}}},
        "required": ["варіанти"],
        "additionalProperties": False,
    }


# Найкоротший запит, з яким по довідник узагалі варто йти. Число не з голови: `lexicon_kb`
# розвʼязує форму за стемом у ЧОТИРИ літери, тож коротший запит там не має чого зачепити.
LOOKUP_MIN = 4
# Що зрізаємо з країв, перш ніж дивитись на запит: партитура подекуди бере слово в лапки або
# лишає кому з речення, а це те саме слово, а не інший запит.
LOOKUP_EDGES = ".,!?;:«»\"'()[]"


def lookup_word(query: str | None) -> str | None:
    """Чи є в такті СЛОВО, з яким по довідник іти, — і яке саме.

    Довідник села — це словник рідкісної лексики (133 статті, `evalkit/data/lexis-uk.json`): він
    відповідає на слово й ні на що більше. Партитура ж кладе в `запит` що завгодно: заміряно на
    живому шлюзі 2026-08-29 (`viche/score`, MamayLM, чотири теми аудиту, дві хвилі на тему) — з
    23 тактів інструмент стояв у 17, а серед тих 17 запитів слова було два («ідіотизм»,
    «накопичення»), решта — перекази речення («Чи не через нас це вовк голодний почав кошару
    обходити? Щоб,»), склеєні ярлики («прикмети_вовки», «сімнадцять_років_тому») і два порожніх.
    Знайшов довідник на всіх 17 нуль разів, як і на 37 із 37 у чотирьох прогонах аудиту
    (`docs/research/dialogue-audit.md`).

    Тому гейт мовчазний і механічний: одне слово з літер, не коротше за стем. Він НЕ питає, чи
    слово є в довіднику, — це вбило б чесну відмову (`ToolResult.found`), на якій стоїть різниця
    між «сходив і не знайшов» і «не ходив».
    """
    word = (query or "").strip().strip(LOOKUP_EDGES).strip()
    if len(word) < LOOKUP_MIN:
        return None
    if not all(c.isalpha() or c in "\'’-" for c in word):
        return None
    return word


def _thesis(raw, names: set[str] | None = None) -> str:
    """Теза так, як її можна показати мовцеві: один рядок, без риштувань переліку, закрита довжина.

    Номер і імʼя зрізаємо, бо модель віддає їх назад разом із тезою: живий шлюз на переліку
    «1. дід Свирид — пригадай схожий випадок» вертає «1. дід Свирид — жаль вовка, треба зрозуміти
    причину» — той самий закон копіювання, лише всередині партитури. Імʼя в тезі означало б
    звертання в чужому пакеті, а номер — службовий рядок у бульбашці.

    Обрізаємо теж тут, а не покладаємось на схему: `maxLength` тримає СТРОГИЙ ярус шлюзу, а він не
    завжди строгий, і задовгий рядок у промпті мовця — це не косметика, а той самий вільний текст,
    який вертається дослівно.

    Порожня теза не викидає такту. Такт — це чиясь черга говорити, і втратити її через мовчазне
    поле дорожче, ніж лишитись без підказки: без тези пакет мовця виглядає рівно так, як виглядав
    доти, тобто самим імʼям адресата.
    """
    text = re.sub(r"^\s*\d+\s*[.)]\s*", "", " ".join(str(raw or "").split()))
    low = text.lower()
    for name in sorted(names or (), key=len, reverse=True):
        if name and low.startswith(name.lower()):
            rest = text[len(name):].lstrip()
            if rest[:1] in "—–-:,":
                text = rest[1:].lstrip()
            break
    return text[:THESIS_MAX]


def repair_score(raw: dict | None, roles: list[str], tools: list[str],
                 standing: dict[str, float] | None = None, tag: str = "т") -> list[Beat]:
    """Лагодить КОД, не модель: чужа роль, невідомий хід, посилання в майбутнє — усе відкидається.

    Схема це вже гарантує на строгому ярусі, але шлюз не завжди строгий, а мовчазний дефект
    інструмента дорожчий за зайву перевірку.

    ★ Тут-таки МЕЖА систем координат, і вона одна на все віче. Модель нумерує такти всередині
    хвилі, яку зараз пише, — інакше вона не вміє, бо іншої нумерації не бачить. Номер живе рівно
    до цього рядка: далі йде мітка (`tag` робить її неповторною між хвилями), і жоден споживач
    номера більше не бачить. `tag` мусить різнитись від хвилі до хвилі — інакше мітки склеяться і
    посилання другої хвилі влучить у першу.

    ★ Самозвертання відсікається БІЛЯ ДЖЕРЕЛА, а не в пакеті. Партитура шість разів із 34 послала
    мовця до його ж попереднього такту, і `_packet` рятувався тим, що скидав ціль — тобто платив
    за це рядком «ПЕРЕД ТОБОЮ ГОВОРИЛИ» замість адресата. Посилання, яке нікуди не веде, чесніше
    не створювати взагалі.
    """
    beats: list[Beat] = []
    quota: dict[str, int] = {}
    base_cap = max(2, int(MAX_BEATS * MAX_SHARE))
    # ★ Репутація = ЧАС СЛОВА. Кому спростували чутку, того слухають менше — не метафорично, а
    # буквально меншою квотою тактів. Рахує код: це визначено даними, а не судженням моделі.
    caps = {r: max(1, round(base_cap * (standing or {}).get(r, 1.0))) for r in roles}
    for item in (raw or {}).get("такти") or []:
        if not isinstance(item, dict):
            continue
        who, move = str(item.get("хто") or ""), str(item.get("хід") or "")
        if who not in roles or move not in MOVES:
            continue
        if quota.get(who, 0) >= caps.get(who, base_cap):
            continue
        quota[who] = quota.get(who, 0) + 1
        reply = item.get("у_відповідь")
        aim = beats[reply - 1] if isinstance(reply, int) and 1 <= reply <= len(beats) else None
        mark = aim.мітка if aim is not None and aim.хто != who else None
        tool = item.get("інструмент")
        tool = str(tool) if tool in tools else None
        deed = str(item.get("дія") or "")
        if deed not in DEEDS:
            deed = DEED_OF_MOVE.get(move, "стоїть")  # дію, визначену ходом, ставить код
        beats.append(Beat(хто=who, хід=move, дія=deed, мітка=f"{tag}:{len(beats) + 1}",
                          у_відповідь=mark, інструмент=tool,
                          запит=str(item.get("запит")) if item.get("запит") else None))
        if len(beats) >= MAX_BEATS:
            break
    return beats


def guest_beats(said_index: int, roles: list[str], recent: list[str], seed: int,
                text: str, mark: str = "") -> list[Beat]:
    """Хто відгукнеться на слово гостя — вирішує КОД.

    Спокуса була перепланувати всю партитуру Mamay'єм на кожну твою репліку. Це виклик дорогого
    слота на кожне натискання, а вибір тут визначений даними: беремо тих, хто щойно НЕ говорив, щоб
    відповідали не ті самі двоє.

    `said_index` лишається сідом кубика (та сама репліка гостя — ті самі відгукувачі), а адресу
    несе `mark`: слово гостя теж дістає мітку, бо інакше воно було б єдиним, на що не можна
    послатись стійко.
    """
    rng = random.Random(f"{seed}:guest:{said_index}:{text[:40]}")
    fresh = [r for r in roles if r not in recent[-2:]] or list(roles)
    rng.shuffle(fresh)
    return [Beat(хто=r, хід=ANSWER_GUEST, дія="підходить", мітка=f"гість:{said_index}:{i + 1}",
                 у_відповідь=mark or None)
            for i, r in enumerate(fresh[:GUEST_REPLIES])]


def chain_depths(beats: list[Beat]) -> list[int]:
    """Глибина кожного такту в ланцюгу відповідей: 0 — почин, 1 — відповідь, 2 — відповідь на неї.

    Рахується по тій самій МІТЦІ, що вже несе адресу (`Beat.у_відповідь`), тож окремого стану для
    цього не заводиться: довідник мітка→глибина живе рівно поки триває лічба. Посилання в
    майбутнє неможливе за побудовою — мітка кладеться в довідник після того, як такт пошукав
    чужу, — а посилання, яке нікуди не веде (ціль викинули), знову робить такт почином.
    """
    seen: dict[str, int] = {}
    out: list[int] = []
    for beat in beats:
        deep = seen[beat.у_відповідь] + 1 if beat.у_відповідь in seen else 0
        out.append(deep)
        if beat.мітка:
            seen[beat.мітка] = deep
    return out


def chain_alive(deep: int, zero: int, free: int = CHAIN_FREE) -> float:
    """Охота відповісти на такт глибини `deep`: повна до `free`, далі рівно вниз, нуль на `zero`.

    Крива взята числом, а не смаком. Заміряно на восьми збережених прогонах: посилання платить за
    себе до другої ланки (зчеплення 64.7%) і на третій уже не платить (28.6% проти 20.0% у реплік
    зовсім без посилання). Тому до `CHAIN_FREE` шанс не рухається взагалі, а між ним і `zero`
    спадає рівними частками — на `zero=4` це 0.5 на третій ланці й нуль на четвертій.
    """
    if deep <= free:
        return 1.0
    if deep >= zero:
        return 0.0
    return (zero - deep) / (zero - free)


def damp_chain(beats: list[Beat], seed: int, topic: str, zero: int,
               free: int = CHAIN_FREE) -> list[Beat]:
    """Ланцюг відповідей ЗГАСАЄ з глибиною: третя-четверта відповідь поспіль здебільшого не лунає.

    ★ Це «bounded autonomy» (arXiv:2604.04703), єдиний механізм із огляду поля, заміряний у живій
    багатокористувацькій грі: ймовірність відповіді спадає з кожним переходом і сягає нуля на
    шостій ланці, і з ним 20 прогонів із 20 завершились природно проти 0 із 20 без нього. Нам він
    підходить формою: рішення тут НЕТЕКСТОВЕ (такт лунає чи ні), тож у пакет не потрапляє ані
    слова, а всі п'ятнадцять випадків, де код уже відібрав вибір у моделі, спільні саме цим.

    Кубик той самий, що вже кидає `scatter`: сід і тема дають ті самі згаслі такти, інакше
    прогони перестали б порівнюватись. Гасне не лише сам такт, а й усе, що на нього посилалось:
    ланцюг обривається, а не лишає сиріт, які показують на мітку, якої вже немає.

    Почин не гасне НІКОЛИ (`free` не менший за 1), тож хвиля не буває порожньою: перший такт
    партитури почин за побудовою (`repair_score` не дає йому цілі), а порожня хвиля обірвала б
    усе віче на наступному ж такті.
    """
    if zero <= free or len(beats) < 2:
        return beats
    rng = random.Random(f"{seed}:{topic}:згасання")
    seen: dict[str, int] = {}
    gone: set[str] = set()
    out: list[Beat] = []
    for beat in beats:
        if beat.у_відповідь in gone:
            gone.add(beat.мітка)
            continue
        deep = seen[beat.у_відповідь] + 1 if beat.у_відповідь in seen else 0
        if rng.random() >= chain_alive(deep, zero, free):
            gone.add(beat.мітка)
            continue
        if beat.мітка:
            seen[beat.мітка] = deep
        out.append(beat)
    return out or beats[:1]


def scatter(beats: list[Beat], roles: list[str], seed: int, topic: str,
            people: dict | None = None, heat: float = 1.0,
            bonds: dict | None = None, chain_zero: int | None = None) -> list[Beat]:
    """Збурення партитури кубиком за сідом — джерело спонтанності, яке НЕ вимагає вибору моделі.

    Той самий сід і та сама тема дають ті самі перебивки: несподіванка для глядача, відтворюваність
    для заміру.

    ★ `chain_zero` — згасання ланцюга відповідей, і судить воно ПАРТИТУРУ, тобто йде перед
    кубиком перебивок. Перебивка — одна ланка вбік і власний кубик норову, а не продовження
    суперечки; гасити її тим самим правилом означало б рахувати спонтанність кроком розмови.
    `None` лишає партитуру недоторканою, байт-у-байт як доти.
    """
    if chain_zero:
        beats = damp_chain(beats, seed, topic, chain_zero)
    if len(beats) < 2:
        return beats
    rng = random.Random(f"{seed}:{topic}")
    out: list[Beat] = []
    added = 0
    for beat in beats:
        out.append(beat)
        speaker = people.get(beat.хто) if people else None
        chance = (interrupt_chance(speaker) if speaker else INTERRUPT_P) * heat
        if added >= MAX_INTERRUPTS or rng.random() > chance:
            continue
        others = [r for r in roles if r != beat.хто]
        if not others:
            continue
        # Перебиває не хто попало: вага норову вирішує, кому дістанеться слово поперек черги.
        if people:
            pool = [r for r in others if r in people]
            # ★ Стосунки міняють, ХТО влізе поперек: хто вже сварився з мовцем, тягнеться
            # перебити його. Без цього сварка лишалась би записом у базі, а не поведінкою.
            weights = []
            for r in pool:
                w = max(0.05, interrupt_chance(people[r]))
                if bonds is not None:
                    w *= 1.0 + max(0.0, -bonds.get(tuple(sorted((r, beat.хто))), 0.0)) * 0.3
                weights.append(w)
            who = rng.choices(pool, weights=weights)[0] if pool else rng.choice(others)
        else:
            who = rng.choice(others)
        added += 1
        # Перебивка вказує на МІТКУ того, кого перебиває, а не на його місце в списку: сам список
        # тут-таки й росте, тож номер у ньому застаріває на наступному ж такті.
        out.append(Beat(хто=who, хід=INTERRUPT_MOVE, дія="підходить",
                        мітка=f"{beat.мітка}+п" if beat.мітка else "",
                        у_відповідь=beat.мітка or None))
    return out
