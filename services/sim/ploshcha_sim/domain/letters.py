"""Письмо гостя зводиться до ОДНОГО вигляду перед перевірками — а на сцену йде оригінал.

Чому це окремий модуль, а не ще один рядок у гейтах. Списки коренів (`domain/viche.py`) написані
однією орфографією: малими літерами, кирилицею, з апострофом. Люди пишуть інакше — і це не здогад,
а замір на живому корпусі з 74 тем, написаних так, як пишуть у Дошку: «мене бье чоловік» (ь замість
апострофа), «Мене бье чоловiк» (латинська «i» всередині кириличного слова), «МЕНЕ БЄ ЧОЛОВІК»
(апостроф просто не набрали), «vbyu susida, yak shche raz pustyt khudobu» (уся тема латиницею).
Жодного з них передфільтр `suspect` не впізнавав, тобто тверде ядро мовчало, а на закритому шві
(`sense=False`) мовчало все віче.

Дописати ці форми коренями не можна: одрука, латиниця й регістр — не сім пропущених слів, а
множення вже наявних. Тому зводиться не список, а ПИСЬМО, і зводиться один раз, в одному місці.

Межа тут головна й вона одна: нормалізується текст ДЛЯ ПЕРЕВІРОК. Ані сцена, ані промпти, ані
памʼять села нормалізованого рядка не бачать — інакше ми переписали б людині її слова, а «GitHub» у
мирній темі приїхав би на екран кирилицею.
"""

import re

# Слово = суцільний пробіг літер. Апостроф навмисно НЕ літера: він тут не звук, а знак письма, і
# нижче зникає зовсім.
_WORD = re.compile(r"[^\W\d_]+", re.UNICODE)

# Апостроф у Дошці набирають чим завгодно: типографським, українським модифікатором, машинописним,
# зворотним лапком, акутом. Заміряно в цьому репозиторії: «`» 2 508 разів, «'» 1 094, «ʼ» 491,
# «’» 13, «´» 1.
APOSTROPHES = "'’ʼ`´‘′"

CYRILLIC = frozenset("абвгґдеєжзиіїйклмнопрстуфхцчшщьюяАБВГҐДЕЄЖЗИІЇЙКЛМНОПРСТУФХЦЧШЩЬЮЯ")

# ★ Двійники — це літери з ОДНАКОВОЮ формою, а не з однаковим звуком.
#
# Малих таких пар рівно вісім: a/а, c/с, e/е, i/і, o/о, p/р, x/х, y/у. Великих більше, бо велика
# латинська B, H, K, M, T на вигляд не відрізняється від В, Н, К, М, Т, тоді як малі b, h, k, m, t
# від б, н, к, м, т відрізняються. Через це заміна робиться ДО зведення регістру: інакше «BОДА»
# перетворилась би на «bода» й двійника в ній уже ніхто не побачив би.
#
# На живому корпусі з 74 тем трапилась одна така літера — латинська «i» в «чоловiк», — і саме вона
# лишала гейт сліпим. Решта пар стоїть тим самим правилом форми й перевірена тестом.
TWINS_LOWER: dict[str, str] = {
    "a": "а", "c": "с", "e": "е", "i": "і", "o": "о", "p": "р", "x": "х", "y": "у",
}
TWINS_UPPER: dict[str, str] = {
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "I": "І", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
}
TWINS: dict[str, str] = TWINS_LOWER | TWINS_UPPER

# ★ «бье» замість «бʼє» — не описка, а перенесене російське письмо, і воно однозначне.
#
# Мʼякий знак перед йотованим не пишеться після ГУБНИХ і «р» — тобто рівно там, де українська
# ставить апостроф, — і саме тому правило звужене до них. Заміряно 2026-08-27 по репозиторію без
# `services/sim` (1 302 981 слово; сам сервіс викинуто, бо інакше корпус міряв би власні тести цієї
# одруки): пара «губний або р + ь + йотоване» трапилась 18 разів, і всі вісімнадцять — сама ця
# одрука в «бье». Після решти приголосних та сама пара трапилась 71 раз і жодного разу не є
# одрукою: «редьюсер» (д), «віньєтка» (н), «мільярдів» (л), «досьє» (с), «Васильевич» (л) —
# правило їх не чіпає.
#
# Давніший запис на цьому місці («по 240 354 словах — «ья», «ьє», «ьї» не трапились жодного разу»)
# сьогодні неправдивий і в числі, і в суті: корпус виріс, а «ья»/«ьє» в ньому є («мільярдів»,
# «альянсів», «віньєтка», «досьє») — просто після приголосних, яких це правило не бере.
_SOFT_TYPO = re.compile("([бпвмфр])ь([яюєїе])")
# «е» після мʼякого знака — це та сама передача «є»: «бье» це «бʼє», а не «бʼе».
_SOFT_VOWEL = {"я": "я", "ю": "ю", "є": "є", "ї": "ї", "е": "є"}

# ★ Транслітерація застосовується до СУЦІЛЬНО латинського рядка, і тільки до нього.
#
# Причина не в обережності, а в тому, що мішаний рядок має український кістяк: латинське слово в
# ньому — назва («GitHub», «Meow»), а не переписане речення, і кирилиця з нього була б вигадкою.
# Порядок пар — від довгих до коротких, бо «shch» мусить прочитатись раніше за «sh», а «yu»
# раніше за «y». Кістяк таблиці — офіційна українська латиниця (постанова КМУ №55, 2010)
# навиворіт; літери, яких у ній немає зовсім (c, g, j, q, w, x), дописані за звуком, бо в Дошку
# пишуть не за постановою, а як на клавіатурі вийде.
TRANSLIT: tuple[tuple[str, str], ...] = (
    ("shch", "щ"), ("sch", "щ"), ("zgh", "зг"),
    ("zh", "ж"), ("kh", "х"), ("ts", "ц"), ("ch", "ч"), ("sh", "ш"),
    ("yu", "ю"), ("ya", "я"), ("ye", "є"), ("yi", "ї"), ("yo", "йо"),
    ("iu", "ю"), ("ia", "я"), ("ie", "є"),
    ("a", "а"), ("b", "б"), ("v", "в"), ("h", "г"), ("g", "ґ"), ("d", "д"), ("e", "е"),
    ("z", "з"), ("y", "и"), ("i", "і"), ("j", "й"), ("k", "к"), ("l", "л"), ("m", "м"),
    ("n", "н"), ("o", "о"), ("p", "п"), ("r", "р"), ("s", "с"), ("t", "т"), ("u", "у"),
    ("f", "ф"), ("c", "ц"), ("w", "в"), ("q", "к"), ("x", "кс"),
)
_TRANSLIT = dict(TRANSLIT)
_TRANSLIT_MAX = max(len(lat) for lat in _TRANSLIT)


def has_cyrillic(text: str) -> bool:
    """Чи є в рядку хоч одна кирилична літера — на цьому стоїть межа транслітерації."""
    return any(ch in CYRILLIC for ch in text or "")


def _untwin(text: str) -> str:
    """Двійники міняються лише в словах, де кирилиця ВЖЕ є: «GitHub» не чіпається, «чоловiк» — так."""
    return _WORD.sub(
        lambda m: ("".join(TWINS.get(ch, ch) for ch in m.group(0))
                   if has_cyrillic(m.group(0)) else m.group(0)),
        text or "")


def fold(text: str) -> str:
    """Читабельне зведення письма: двійники, регістр, один апостроф, «бье» → «бʼє», зайві пробіли.

    Вертає рядок, який ще можна прочитати очима, — саме ним зручно бачити, що нормалізатор зробив.
    Перевірки порівнюються не з ним, а з `for_checks`, де апострофа немає зовсім.
    """
    low = _untwin(text or "").lower()
    for ch in APOSTROPHES:
        low = low.replace(ch, "'")
    low = _SOFT_TYPO.sub(lambda m: f"{m.group(1)}'{_SOFT_VOWEL[m.group(2)]}", low)
    return " ".join(low.split())


def transliterate(text: str) -> str:
    """Латиниця в кирилицю — і лише тоді, коли кирилиці в рядку немає ЖОДНОЇ.

    «vbyu susida, yak shche raz pustyt khudobu» стає «вбю сусіда, як ще раз пустит худобу», тобто
    тверде ядро бачить обіцянку скалічити названу людину й закриває віче за нуль токенів. Мішаний
    рядок вертається як був: у ньому латинське слово — назва, а не переписане речення.
    """
    if not text or has_cyrillic(text):
        return text or ""
    out, i, low = [], 0, text.lower()
    while i < len(low):
        for size in range(_TRANSLIT_MAX, 0, -1):
            cyr = _TRANSLIT.get(low[i:i + size])
            if cyr is not None:
                out.append(cyr)
                i += size
                break
        else:
            out.append(low[i])
            i += 1
    return "".join(out)


def for_checks(text: str) -> str:
    """ОДИН вигляд, з яким звіряються всі закриті списки: без апострофа, без регістру, кирилицею.

    Апостроф тут не зводиться до одного знака, а зникає, і це замір, а не смак. Списки написані з
    ним («бʼє», «вбʼю»), а люди його не набирають («бє», «вбю») або замінюють мʼяким знаком
    («бье») — три написання одного слова. По 240 354 словах цього репозиторію знайшлась рівно ОДНА
    пара слів, які зливаються від викидання апострофа: «вбю» і «вбʼю», обидва з `HARM_ROOTS`, де
    вони й лежали дублікатом саме через брак цього зведення. Тобто ціна нульова, а виграш — увесь
    клас одрук.

    Порядок кроків не переставляється: двійники до регістру (велика «B» це «В», мала «b» — ні),
    транслітерація після зведення (інакше «чоловiк» з латинською «i» вважався б латинським словом).
    """
    return transliterate(fold(text)).replace("'", "")
