def ids_for(document: str) -> list[str]:
    return [pid for pid, p in PARAGRAPHS.items() if p["документ"] == document]


def has_year(text: str) -> bool:
    return any(str(y) in text for y in range(1800, 1960))


def crafts_in(text: str) -> list[str]:
    """Через леми, а не підрядком: у тексті «ткалю», а в переліку «ткаля» — вісь U6."""
    from .tools_fake import _lemma_set
    words = _lemma_set(text)
    return [c for c in CRAFTS if _lemma_set(c) & words]


def mentions(document: str, needle: str) -> list[str]:
    low = needle.casefold()
    return [pid for pid in ids_for(document) if low in PARAGRAPHS[pid]["текст"].casefold()]
