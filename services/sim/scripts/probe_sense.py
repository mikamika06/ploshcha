def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="суддя змісту: точність, токени, латентність")
    p.add_argument("--model", default="MAMAY_MODEL",
                   help="змінна оточення з іменем моделі: MAMAY_MODEL або LAPA_MODEL")
    p.add_argument("--max-tokens", type=int, default=SENSE_TOKENS)
    p.add_argument("--seed", type=int, default=1)
    args = p.parse_args(argv or sys.argv[1:])

    key, url = os.environ.get("LAPA_API_KEY"), os.environ.get("LAPA_BASE_URL")
    if not key or not url:
        print("нема LAPA_API_KEY / LAPA_BASE_URL у .env")
        return 2
    llm = OpenAICompatLlm(model=os.environ[args.model], base_url=url, api_key=key,
                          structured_mode="json_schema")
    schema = sense_schema()

    rows, latencies = [], []
    ok = paid = 0
    for text, want in CASES:
        # Передфільтр рахуємо тут же: без нього незрозуміло, за які рядки село взагалі платить.
        band = suspect(text, _SPEAKERS)
        started = time.perf_counter()
        res = llm.generate_structured(sense_prompt(text), schema, system=SENSE_SYSTEM,
                                      temperature=0.0, max_tokens=args.max_tokens, seed=args.seed)
        latency = int((time.perf_counter() - started) * 1000)
        latencies.append(latency)
        try:
            data = json.loads(res.text)
        except Exception:
            data = {"присуд": f"НЕРОЗБІРНО: {res.text[:60]!r}", "підстава": ""}
        got = str(data.get("присуд"))
        ok += got == want
        paid += band is not None
        rows.append({"рядок": text, "смуга": band, "хотіли": want, "дістали": got,
                     "підстава": data.get("підстава"), "вхід": res.usage.prompt_tokens,
                     "вивід": res.usage.completion_tokens, "обрив": res.finish_reason,
                     "мс": latency})
        print(f"{'OK  ' if got == want else 'МИМО'} смуга={str(band):10} хотіли={want:20} "
              f"дістали={got[:20]:20} вх={res.usage.prompt_tokens:4} "
              f"вив={res.usage.completion_tokens:3} {res.finish_reason:6} {latency:5}мс "
              f"| {text[:40]}")

    n = len(CASES)
    total_in = sum(r["вхід"] for r in rows)
