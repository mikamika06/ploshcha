def _load_env():
    env = ROOT / ".env"
    if not env.exists():
        return
    for line in env.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip())


def _judge():
    """Суддя питає МАМАЯ, і це не деталь конфігурації.

    Заміряно: Lapa на тому самому промпті дала 13/14, і промах був саме в НАПРЯМКУ дії («Убʼю того
    злодія, як спіймаю» → самоушкодження), тобто гість дістав би 7333 замість 102. Тому крок іде
    видом `judge` (`MAMAY_KINDS`), і живий контракт міряє ту саму модель, що й прод.
    """
    _load_env()
    base_url = os.environ.get("PLOSHCHA_LIVE_URL") or os.environ.get("LAPA_BASE_URL")
    model = os.environ.get("MAMAY_MODEL")
    key = os.environ.get("LAPA_API_KEY", "EMPTY")
    if not base_url or not model:
        pytest.skip("нема endpoint: задай PLOSHCHA_LIVE_URL/MAMAY_MODEL або LAPA_*")
    from ploshcha_sim.adapters.llm_openai import OpenAICompatLlm
    return OpenAICompatLlm(model=model, base_url=base_url, api_key=key,
                           structured_mode="json_schema", timeout=300.0)


def _verdict(llm, text: str, seed: int = SENSE_SEED) -> str:
    res = llm.generate_structured(sense_prompt(text), sense_schema(), system=SENSE_SYSTEM,
                                  temperature=0.0, max_tokens=SENSE_TOKENS, seed=seed)
    assert res.finish_reason != "length", f"стеля 96 замала для: {text}"
    data = json.loads(res.text)
    assert data["присуд"] in SENSE_VERDICTS, f"шосте значення на: {text}"
    assert len(data["підстава"]) <= 80, "шлюз мусить тримати maxLength, а не прохання в промпті"
    assert set(data) == {"присуд", "підстава"}, "additionalProperties: False"
    return data["присуд"]


