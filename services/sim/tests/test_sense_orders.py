def _verdicts(text: str, raw: str, without: str) -> dict[str, str]:
    """Присуди цього рядка так, як їх зняв живий шлюз: сирий завжди, без прольотів — коли є що різати."""
    table = {text: raw}
    if without:
        table[blank_orders(text, spoken=True)] = without
    return table


