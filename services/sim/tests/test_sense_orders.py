class Replay(FakeLlm):
    """Суддя, який віддає ЗАМІРЯНИЙ присуд саме на той рядок, який йому дали.

    Черга тут не годиться: рядків судиться два (сирий і без прольотів наказу), і лінійний скрипт
    сховав би те єдине, що судиться, — ЩО саме поїхало до судді.

    Рядок, якого в заміряній таблиці немає, віддає «безпечно» й лишається в `stray`: у повному
    прогоні судиться ще й вивід села (хроніка, чутка, ухвала), і той вивід складає сам фейк, а не
    замір. Кидати з фейка виняток тут не можна — `_sense` ловить його як збій каналу, і тест читав
    би вигоряння замість присуду.
    """

    def __init__(self, verdicts: dict[str, str], rest: list[str] | None = None):
        super().__init__(list(rest or []), model="fake")
        self.verdicts = dict(verdicts)
        self.judged: list[str] = []
        self.stray: list[str] = []
        self._rest = list(rest or [])

    def _next(self, prompt, system, structured, schema, seed, temperature=0.0, max_tokens=0):
        props = (schema or {}).get("properties") if isinstance(schema, dict) else None
        if props and "присуд" in props:
            for line, verdict in self.verdicts.items():
                if prompt == sense_prompt(_ends(line)):
                    self.judged.append(line)
                    self._responses = [json.dumps({"присуд": verdict, "підстава": "замір"},
                                                  ensure_ascii=False)]
                    break
            else:
                self.stray.append(prompt)
                self._responses = [json.dumps({"присуд": "безпечно", "підстава": "вивід села"},
                                              ensure_ascii=False)]
        elif props and "голос" in props:
            self._responses = ['{"голос": "за", "чому": "бо село так вирішило"}']
        else:
            self._responses = [self._rest.pop(0)] if self._rest else []
        return super()._next(prompt, system, structured, schema, seed, temperature, max_tokens)


def _judged(llm, text: str | None = None) -> list[dict]:
    """Виклики судді — за СХЕМОЮ, а не за порядком; `text` звужує їх до присудів про один рядок."""
    return [c for c in llm.calls
            if "присуд" in ((c.get("schema") or {}).get("properties") or {})
            and (text is None or text in (c.get("prompt") or ""))]


def build(verdicts, *, rest=None, trace=None, width=2):
    """Віче в прод-умові гейтів: ніж охорони той самий, що складає `build_viche_guard`."""
    llm = Replay(verdicts, rest)
    agent = Viche(single_model_router(llm), PresetEffort(), None, width=width, run_id="r",
                  trace=trace, guard=build_viche_guard(AppSpec(viche_guard=True)), sense=True)
    agent.plan_ahead = False
    return agent, llm


