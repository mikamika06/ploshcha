const CLOSERS = [
  "Гаразд — поміркуймо ще й вирішимо гуртом.",
  "На тому й станемо, а завтра докінчимо.",
  "Розійдімося, та думки лишімо при собі до ради.",
];

function pick<T>(a: T[]): T {
  return a[(Math.random() * a.length) | 0];
}
function shuffle<T>(a: T[]): T[] {
  const r = [...a];
  for (let i = r.length - 1; i > 0; i--) {
    const j = (Math.random() * (i + 1)) | 0;
    [r[i], r[j]] = [r[j], r[i]];
  }
  return r;
}

/** Будує послідовність реплік гурту на тему: заспів → реакції кожного (у своєму голосі) → підсумок старшого. */
export function discussionFor(topic: string, parts: TalkPart[]): DiscussionLine[] {
  if (!parts.length) return [];
  const order = shuffle(parts);
  const usedGeneric = shuffle(GENERIC);
  const lines: DiscussionLine[] = [];
  lines.push({ ...order[0], text: pick(OPENERS)(topic) });
  order.slice(1).forEach((p, i) => {
    const voiced = VOICED[p.role];
    const text = voiced ? pick(voiced) : usedGeneric[i % usedGeneric.length];
    lines.push({ ...p, text });
  });
  const elder = order.find((p) => p.role === "starosta" || p.role === "did" || p.role === "pip") ?? order[0];
  lines.push({ ...elder, text: pick(CLOSERS) });
  return lines;
}
